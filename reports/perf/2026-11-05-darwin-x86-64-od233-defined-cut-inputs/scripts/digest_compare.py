"""Compare the head's sweep digests with slice 25's base (review round, OD-233).

The head's sweep (`defined_cut_inputs_never_stop_a_part_holding`) prints, for
every fixture of slices 1 to 25 and of the od233 module at every block start
and every clean point,
`OD233_SWEEP_DIGEST<TAB>label<TAB>cut<TAB>off=D<TAB>on=D<TAB>defined=(b, i)<TAB>merged=M`;
the base recorder (`od233_base_digests`, generated by
`fails-before/make_fails_before.py ... base` and run at b30110fcd) prints
`OD233_BASE_DIGEST<TAB>label<TAB>cut<TAB>D`, where D is a statement digest or
`refused: <text>`. This requires, for every subject: the head without the rule
(`od233-off`) equal to the base, and the head with the rule equal to the base
wherever nothing is defined. It prints every mismatch and the counts, and
exits 1 on any mismatch, on a subject only one side has, or on a line it
cannot read.
Usage: python3 -I digest_compare.py <base log> <head log>
"""
import re
import sys

BASE = re.compile(r"OD233_BASE_DIGEST\t([^\t]*)\t([^\t]*)\t(.*)$")
HEAD = re.compile(
    r"OD233_SWEEP_DIGEST\t([^\t]*)\t([^\t]*)\toff=(.*)\ton=(.*)\tdefined=\((\d+), (\d+)\)\tmerged=(.*)$"
)


def read(path, pattern, marker):
    rows, unread = {}, []
    with open(path, encoding="utf-8", errors="replace") as handle:
        for line in handle:
            line = line.rstrip("\n")
            at = line.find(marker)
            if at < 0:
                continue
            match = pattern.match(line[at:])
            if not match:
                unread.append(line[:200])
                continue
            key = (match.group(1), match.group(2))
            if key in rows:
                unread.append(f"repeated subject {key}")
            rows[key] = match.groups()[2:]
    return rows, unread


def main():
    base, base_unread = read(sys.argv[1], BASE, "OD233_BASE_DIGEST")
    head, head_unread = read(sys.argv[2], HEAD, "OD233_SWEEP_DIGEST")
    bad = [f"base line not read: {line}" for line in base_unread]
    bad += [f"head line not read: {line}" for line in head_unread]
    for key in sorted(set(base) ^ set(head)):
        bad.append(f"only in {'base' if key in base else 'head'}: {key}")
    off_equal = on_equal = defining = 0
    for key in sorted(set(base) & set(head)):
        (digest,) = base[key]
        off, on, bytes_, items, _merged = head[key]
        if off == digest:
            off_equal += 1
        else:
            bad.append(f"{key}: od233-off {off[:80]} != base {digest[:80]}")
        if (bytes_, items) == ("0", "0"):
            if on == digest:
                on_equal += 1
            else:
                bad.append(f"{key}: nothing defined, but {on[:80]} != base {digest[:80]}")
        else:
            defining += 1
    print(
        f"DIGEST_COMPARE subjects base={len(base)} head={len(head)} "
        f"off_equal_to_base={off_equal} defining={defining} "
        f"undefined_on_equal_to_base={on_equal} mismatches={len(bad)}"
    )
    for line in bad:
        print(f"DIGEST_COMPARE mismatch: {line}")
    sys.exit(1 if bad else 0)


main()
