#!/usr/bin/env python3
"""Generate a matched callee/caller pair for a cross-backend ABI differential.

Author: Andrew Yates <andrewyates.name@gmail.com>
Copyright 2026 Andrew Yates | License: Apache-2.0

WHY: every other differential gate in this repo compiles a WHOLE PROGRAM with a
single backend, so a calling-convention disagreement is invisible to all of them
-- both sides are wrong in the same way and agree with each other. The AArch64
stack-argument layout bug (Darwin natural-size packing applied to an ELF target,
where AAPCS64 stage C.14 mandates 8-byte slots) was found only by linking an
LLVM-compiled caller against a trust-cg-compiled callee.

Each seed emits a signature of 9..20 arguments using narrow and mixed-width
types where the two conventions disagree. Most seeds overflow one of the 8 GPR /
8 FPR argument banks onto the stack -- which is where the layout rules diverge
-- and the remainder still exercise register assignment. Overflow is frequent
across a seed corpus, not guaranteed per seed.

INVARIANT: callee and caller are generated by two SEPARATE invocations sharing
one seed, so they agree only because the draw sequence below is identical for
both roles. Do not add, remove or reorder any rng call without regenerating the
pinned corpus figures in README.md.
"""

import random
import sys

# (rust type, inclusive low bound, inclusive high bound)
INT_TYPES = [
    ("u8", 0, 255),
    ("i8", -128, 127),
    ("u16", 0, 65535),
    ("i16", -32768, 32767),
    ("u32", 0, 4_000_000),
    ("i32", -2_000_000, 2_000_000),
    ("u64", 0, 9_000_000),
    ("i64", -9_000_000, 9_000_000),
    # 128-bit integers are here for their ALIGNMENT, not their width. AAPCS64
    # stage C.8 rounds the GPR index up to an EVEN register before allocating
    # the pair, so `(ptr, i128, i128)` lands at x0, x2:x3, x4:x5 and leaves x1
    # permanently dead. trust-cg omitted that round-up and packed them at
    # x1:x2 / x3:x4 -- see the C.8 note in trust-cg-lower/src/abi.rs. Both
    # sides of a trust-cg-only call agreed with each other, so only a
    # cross-backend differential like this one can see it.
    ("u128", 0, 2**100),
    ("i128", -(2**100), 2**100),
]
# Types whose value does not fit in a u64 and must be folded in two halves.
WIDE_TYPES = {"u128", "i128"}

# A 16-byte-ALIGNED aggregate. This is a distinct code path from the scalar
# above -- the classifier handles composites in their own arm -- and the C.8
# round-up has to be applied in both. Its 8-aligned sibling is the negative
# control: same 16 bytes, and it must NOT skip a register.
AGG_DECL = """#[repr(C)]
#[derive(Clone, Copy)]
pub struct A16 {
    pub x: i128,
}

#[repr(C)]
#[derive(Clone, Copy)]
pub struct A8 {
    pub a: i64,
    pub b: i64,
}

#[repr(C)]
#[derive(Clone, Copy)]
pub struct A24 {
    pub a: i64,
    pub b: i64,
    pub c: i64,
}
"""
AGG_TYPES = ["A16", "A8"]
FLOAT_TYPES = ["f32", "f64"]

# Return values cross the same boundary as arguments and take DIFFERENT paths:
# x0 for a scalar, x0:x1 for a 128-bit pair, and an indirect sret buffer whose
# pointer arrives in x8 for anything over 16 bytes. A gate that always returns
# u64 exercises exactly one of the three. Each entry is
# (rust type, expression building it from `acc`, expression folding it back).
RET_TYPES = [
    ("u64", "acc", "v"),
    (
        "i128",
        "((acc as i128) << 64) | (acc as i128 & 0xffff_ffff_ffff_ffff)",
        "(v as u64) ^ ((v >> 64) as u64).wrapping_mul(3)",
    ),
    (
        "A16",
        "A16 { x: ((acc as i128) << 64) | (acc as i128 & 0xffff_ffff_ffff_ffff) }",
        "(v.x as u64) ^ ((v.x >> 64) as u64).wrapping_mul(3)",
    ),
    (
        "A8",
        "A8 { a: acc as i64, b: (acc as i64).wrapping_mul(3) }",
        "(v.a as u64) ^ (v.b as u64).wrapping_mul(3)",
    ),
    (
        "A24",
        "A24 { a: acc as i64, b: (acc as i64).wrapping_mul(3), c: (acc as i64).wrapping_mul(7) }",
        "(v.a as u64) ^ (v.b as u64).wrapping_mul(3) ^ (v.c as u64).wrapping_mul(7)",
    ),
]


def main() -> int:
    seed = int(sys.argv[1])
    which = sys.argv[2]  # "callee" or "caller"
    rng = random.Random(seed)

    # 9..20 params: pushes past the 8 GPR / 8 FPR argument registers often
    # enough that a stack-slot layout error shows up across a seed corpus.
    nargs = rng.randrange(9, 21)
    params = []
    values = []
    for _ in range(nargs):
        if rng.random() < 0.25:
            ty = rng.choice(FLOAT_TYPES)
            # Small integral values: exactly representable in f32 and f64, so
            # the checksum is bit-identical on both sides.
            value = rng.randrange(-1000, 1000)
            params.append(ty)
            values.append(f"{value}.0{ty}")
        elif rng.random() < 0.15:
            ty = rng.choice(AGG_TYPES)
            params.append(ty)
            if ty == "A16":
                values.append(f"A16 {{ x: {rng.randrange(-(2**100), 2**100)}i128 }}")
            else:
                values.append(
                    f"A8 {{ a: {rng.randrange(-9_000_000, 9_000_000)}i64,"
                    f" b: {rng.randrange(-9_000_000, 9_000_000)}i64 }}"
                )
        else:
            ty, low, high = rng.choice(INT_TYPES)
            value = rng.randrange(low, high + 1)
            params.append(ty)
            values.append(f"{value}{ty}")

    # Identical text serves as the callee's parameter list and the caller's
    # extern declaration; a mismatch between the two would itself be a bug.
    signature = ", ".join(f"p{i}: {ty}" for i, ty in enumerate(params))
    ret_ty, ret_build, ret_fold = rng.choice(RET_TYPES)

    # Order-sensitive checksum: a wrong stack slot changes the result.
    # Floats deliberately take the same `as i64 as u64` path as integers -- the
    # values above are exactly representable, so the cast is lossless and the
    # accumulator stays bit-identical across backends.
    body = ["    let mut acc: u64 = 0;"]
    for i, ty in enumerate(params):
        # Fold every bit that crossed the boundary. A 128-bit value read one
        # register too low still has a plausible LOW half, so checking only
        # `as i64` would let a pair-alignment error through on some values.
        if ty in WIDE_TYPES:
            body.append(f"    acc = acc.wrapping_mul(31).wrapping_add(p{i} as u64);")
            body.append(
                f"    acc = acc.wrapping_mul(31).wrapping_add((p{i} >> 64) as u64);"
            )
        elif ty == "A16":
            body.append(f"    acc = acc.wrapping_mul(31).wrapping_add(p{i}.x as u64);")
            body.append(
                f"    acc = acc.wrapping_mul(31).wrapping_add((p{i}.x >> 64) as u64);"
            )
        elif ty == "A8":
            body.append(f"    acc = acc.wrapping_mul(31).wrapping_add(p{i}.a as u64);")
            body.append(f"    acc = acc.wrapping_mul(31).wrapping_add(p{i}.b as u64);")
        else:
            body.append(
                f"    acc = acc.wrapping_mul(31).wrapping_add(p{i} as i64 as u64);"
            )
    body.append(f"    {ret_build}")

    if which == "callee":
        print(AGG_DECL)
        print("#[no_mangle]")
        print(f'pub extern "C" fn xabi({signature}) -> {ret_ty} {{')
        print("\n".join(body))
        print("}")
    elif which == "caller":
        # Identical decl on both sides; a divergence here would be a harness
        # bug that makes the differential compare two different programs.
        print(AGG_DECL)
        print(f'extern "C" {{ fn xabi({signature}) -> {ret_ty}; }}')
        print("use std::hint::black_box as bb;")
        print("fn main() {")
        args = ", ".join(f"bb({value})" for value in values)
        print(f"    let v = unsafe {{ xabi({args}) }};")
        print(f"    let folded: u64 = {ret_fold};")
        print("    std::process::exit((folded % 251) as i32);")
        print("}")
    else:
        # Fail closed: a typo'd role must not silently emit a caller, which
        # would make the harness compare a program against itself and PASS.
        raise ValueError(f"expected callee or caller, got {which!r}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
