    /// CONTRACT TEST: every `ay` CLI flag trust-cg actually passes must still be
    /// accepted by the installed solver.
    ///
    /// This exists because `--quiet` was silently removed from `ay solve` and
    /// nothing noticed until two cert tests went red with a confusing
    /// downstream failure. `ay` is NOT a pinned dependency — the solver is
    /// resolved by searching PATH and known build directories — so an unpinned
    /// external prover sits in the trust base and its CLI can drift under us at
    /// any time. This turns that drift into one clear, immediate failure that
    /// names the offending flag.
    ///
    /// It deliberately EXERCISES each flag rather than scraping `--help`:
    /// `--dump-bv-cnf` is functional but undocumented, so a help-text check
    /// would report a false positive for it.
    #[test]
    fn ay_cli_still_accepts_every_flag_trust_cg_passes() {
        let Some(ay) = crate::ay_bridge::resolved_solver_path() else {
            eprintln!("ay_cli_still_accepts_every_flag...: no ay resolvable; skipping");
            return;
        };
        let dir = temp_dir("ay_cli_contract");
        std::fs::create_dir_all(&dir).expect("create workdir");
        let smt2 = dir.join("q.smt2");
        std::fs::write(&smt2, GOLDEN_SMT2).expect("write smt2");

        // (label, args) — each is a real invocation shape from this repo.
        let cnf = dir.join("q.cnf");
        let drat = dir.join("q.drat");
        let alethe = dir.join("q.alethe");
        let invocations: Vec<(&str, Vec<String>)> = vec![
            (
                "lrat_cert step 1a (SMT-LIB bit-blast + CNF dump)",
                vec![
                    "solve".into(),
                    smt2.display().to_string(),
                    "--dump-bv-cnf".into(),
                    cnf.display().to_string(),
                    "--no-verify-proof".into(),
                ],
            ),
            (
                "lrat_cert step 1b (DIMACS refutation + DRAT)",
                vec![
                    "solve".into(),
                    cnf.display().to_string(),
                    "--proof".into(),
                    drat.display().to_string(),
                    "--no-verify-proof".into(),
                ],
            ),
            (
                "alethe proof emission",
                vec![
                    "solve".into(),
                    smt2.display().to_string(),
                    "--proof".into(),
                    alethe.display().to_string(),
                    "--proof-format".into(),
                    "alethe".into(),
                ],
            ),
        ];

        for (label, args) in invocations {
            let out = Command::new(&ay)
                .args(&args)
                .output()
                .unwrap_or_else(|e| panic!("spawning ay for {label} failed: {e}"));
            let stderr = String::from_utf8_lossy(&out.stderr);
            let stdout = String::from_utf8_lossy(&out.stdout);
            // We do NOT assert a verdict here — only that the CLI SURFACE is
            // intact. A drifted/removed flag surfaces as clap's "unexpected
            // argument", and a rejected mode as an "Error:" line.
            assert!(
                !stderr.contains("unexpected argument")
                    && !stderr.contains("unrecognized")
                    && !stdout.contains("unexpected argument"),
                "ay CLI DRIFT — trust-cg passes a flag `ay` no longer accepts.\n\
                 invocation: {label}\n  args: {args:?}\n  stderr: {}",
                stderr.trim()
            );
            assert!(
                !stderr.lines().any(|l| l.trim_start().starts_with("Error:")),
                "ay REJECTED a mode trust-cg depends on.\n\
                 invocation: {label}\n  args: {args:?}\n  stderr: {}",
                stderr.trim()
            );
        }

        let _ = std::fs::remove_dir_all(&dir);
    }

    /// A stale CNF left in the workdir by an EARLIER obligation must never be
    /// adopted as this run's output.
    ///
    /// This pins a REAL false-certificate vector, not a hypothetical one. The
    /// dangerous input is a **simplifier-closed** obligation: AY proves it
    /// `unsat` without ever reaching the bit-blaster, so it dumps NO CNF, and
    /// `generate_cert_for_smt2` is supposed to REFUSE to mint (there is no
    /// bit-blasted formula to certify). But the refusal is an `is_file()` check
    /// — so a leftover CNF from a previous obligation satisfies it, the DRAT
    /// step then refutes THAT unrelated formula, `drat-trim` happily verifies
    /// the pair, and the result is a cert whose `verdict_key` names this
    /// obligation while its CNF is a different formula entirely.
    ///
    /// Note the happy path cannot detect this: AY overwrites both artifacts
    /// there, so a stale-artifact test over a normal obligation passes with or
    /// without the fix and proves nothing.
    #[test]
    fn stale_cnf_cannot_certify_a_simplifier_closed_obligation() {
        let Some(ay) = crate::ay_bridge::resolved_solver_path() else {
            eprintln!("stale_cnf_cannot_certify_...: no ay resolvable; skipping");
            return;
        };
        let ay = std::path::PathBuf::from(ay);
        let dir = temp_dir("e2e_stale_simp");
        let workdir = dir.join("gen");
        std::fs::create_dir_all(&workdir).expect("create workdir");

        // `bvadd x y == bvadd x y` is closed by AY's SMT simplifier: it answers
        // unsat at exit 0 and writes no CNF.
        const SIMPLIFIER_CLOSED_SMT2: &str = concat!(
            "(set-logic QF_BV)\n",
            "(declare-const x (_ BitVec 8))\n",
            "(declare-const y (_ BitVec 8))\n",
            "(assert (not (= (bvadd x y) (bvadd x y))))\n",
            "(check-sat)\n"
        );

        // Plant an unrelated but genuinely UNSAT CNF plus a matching DRAT, so
        // every downstream check would succeed on the stale pair.
        let stale_cnf = "p cnf 1 2\n1 0\n-1 0\n";
        std::fs::write(workdir.join("obligation.cnf"), stale_cnf).expect("plant cnf");
        std::fs::write(workdir.join("obligation.drat"), "0\n").expect("plant drat");

        let result = generate_cert_for_smt2(
            "simplifier-closed (bvadd x y == bvadd x y)",
            SIMPLIFIER_CLOSED_SMT2,
            &ay,
            drat_trim(),
            &workdir,
        );

        match result {
            Err(msg) => assert!(
                msg.contains("no DRAT certificate available"),
                "expected the simplifier-closed refusal, got: {msg}"
            ),
            Ok(cert) => panic!(
                "FALSE CERTIFICATE: minted a cert for a simplifier-closed obligation off a \
                 stale CNF ({} bytes); recorded cnf_sha256={}",
                cert.cnf.len(),
                cert.cnf_sha256
            ),
        }

        let _ = std::fs::remove_dir_all(&dir);
    }

    /// END-TO-END (gated on `ay`): certify a GENUINE lowering-VC obligation via
    /// the `ProofObligation` → `db_obligation_smt2` path, and prove the cert's
    /// `verdict_key` equals the tier-0 row key that `verdict_db` would look up
    /// for it — i.e. the cert backs a real Formal verdict, not a toy.
    ///
    /// The VC is the strength-reduction identity `x + x == x << 1` at 8-bit
    /// (double ≡ logical-shift-left-1, the Iadd-double → LSL lowering). Its two
    /// sides are structurally distinct (`bvadd` vs `bvshl`), so ay must actually
    /// BIT-BLAST to refute it — producing the CNF + DRAT that make it
    /// drat-trim-certifiable. (A direct 1:1 lowering like `Iadd -> ADD` is
    /// `add == add`, which ay's simplifier closes WITHOUT bit-blasting, so it
    /// has no DRAT — `generate_cert_for_smt2` correctly returns `Err` for those;
    /// their independent-check lane is the SMT-level Alethe/Lean proof, not
    /// DRAT.)
    #[test]
    fn end_to_end_obligation_binding_via_ay() {
        use crate::smt::SmtExpr;
        let Some(ay) = crate::ay_bridge::resolved_solver_path() else {
            eprintln!("end_to_end_obligation_binding_via_ay: no ay solver resolvable; skipping");
            return;
        };
        let ay = std::path::PathBuf::from(ay);
        let dir = temp_dir("e2e_ob");
        let x = SmtExpr::var("x", 8);
        let ob = crate::lowering_proof::ProofObligation {
            machine_side_provenance: crate::lowering_proof::MachineSideProvenance::StaticDb,
            name: "Idouble_I8 -> LSL#1 (x+x == x<<1)".to_string(),
            trust_ir_expr: x.clone().bvadd(x.clone()),
            aarch64_expr: x.clone().bvshl(SmtExpr::bv_const(1, 8)),
            inputs: vec![("x".to_string(), 8)],
            preconditions: vec![],
            fp_inputs: vec![],
            category: Some(crate::lowering_proof::TransvalCheckKind::InstructionLowering),
        };
        assert!(
            ob.is_genuinely_proven(),
            "the two sides must be structurally distinct (non-degenerate) to force bit-blasting"
        );
        let cert = generate_cert_for_obligation(&ob, &ay, drat_trim(), &dir)
            .expect("x+x == x<<1 is a valid UNSAT lowering VC that bit-blasts and should certify");

        assert!(recheck_cert(&cert, drat_trim(), &dir.join("recheck")).is_verified());

        // The cert's key MUST equal the verdict-DB row key for this obligation.
        let identity = crate::ay_bridge::solver_identity_hash(&ay.to_string_lossy()).unwrap();
        let row_smt2 = crate::verdict_db::db_obligation_smt2(&ob);
        let expected_key = crate::ay_bridge::verdict_cache_key_v2(&identity, &row_smt2);
        assert_eq!(
            cert.verdict_key, expected_key,
            "the LRAT cert must back the exact tier-0 verdict-DB row for this obligation"
        );

        let _ = std::fs::remove_dir_all(&dir);
    }

