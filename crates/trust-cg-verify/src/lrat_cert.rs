// Serialization (recording a cert as a committable artifact)
// ---------------------------------------------------------------------------

/// Serialize a cert to the strict `tcg-lrat-cert-v2` text format. The CNF and
/// DRAT payloads are length-framed (they are multi-line), mirroring the
/// `verdict_db` row framing. Round-trips through [`parse_cert`] before
/// returning, so a renderer bug can never emit a cert the parser would misread.
pub fn render_cert(cert: &LratCert) -> Result<String, String> {
    for (label, v) in [
        ("verdict_key", &cert.verdict_key),
        ("solver_identity", &cert.solver_identity),
        ("cnf_sha256", &cert.cnf_sha256),
    ] {
        if v.len() != 64
            || !v
                .bytes()
                .all(|b| b.is_ascii_hexdigit() && !b.is_ascii_uppercase())
        {
            return Err(format!("{label} must be 64 lowercase hex chars, got {v:?}"));
        }
    }
    if cert.obligation_name.is_empty() || cert.obligation_name.contains('\n') {
        return Err(format!(
            "invalid obligation name {:?}",
            cert.obligation_name
        ));
    }
    if sha256_hex(cert.cnf.as_bytes()) != cert.cnf_sha256 {
        return Err("cnf_sha256 does not match cnf bytes".to_string());
    }

    let mut out = String::new();
    out.push_str(LRAT_CERT_SCHEMA_LINE);
    out.push('\n');
    out.push_str(&format!("verdict-sha256: {}\n", cert.verdict_key));
    out.push_str(&format!("solver-sha256: {}\n", cert.solver_identity));
    out.push_str(&format!("cnf-sha256: {}\n", cert.cnf_sha256));
    out.push_str(&format!("obligation: {}\n", cert.obligation_name));
    out.push_str(&format!("cnf {}\n", cert.cnf.len()));
    out.push_str(&cert.cnf);
    out.push('\n');
    out.push_str(&format!("drat {}\n", cert.drat.len()));
    out.push_str(&cert.drat);
    out.push('\n');
    out.push_str(&format!("smt2 {}\n", cert.smt2.len()));
    out.push_str(&cert.smt2);
    out.push('\n');

    match parse_cert(&out) {
        Ok(parsed) if &parsed == cert => Ok(out),
        Ok(_) => Err("render/parse round-trip mismatch".to_string()),
        Err(e) => Err(format!("rendered cert fails to parse: {e}")),
    }
}

/// Parse a `tcg-lrat-cert-v2` cert. STRICT: any malformed construct is an error
/// (a corrupt cert is never silently half-read). Re-derives and enforces
/// `cnf_sha256` from the recorded CNF bytes, so a cert whose header hash was
/// edited to disagree with its payload is rejected at parse time.
pub fn parse_cert(text: &str) -> Result<LratCert, String> {
    let bytes = text.as_bytes();
    let mut pos = 0usize;

    let next_line = |pos: &mut usize| -> Result<String, String> {
        if *pos >= bytes.len() {
            return Err("unexpected end of cert".to_string());
        }
        let start = *pos;
        let end = bytes[start..]
            .iter()
            .position(|&b| b == b'\n')
            .map(|i| start + i)
            .ok_or_else(|| "missing trailing newline".to_string())?;
        *pos = end + 1;
        String::from_utf8(bytes[start..end].to_vec()).map_err(|_| "non-UTF8 line".to_string())
    };
    let framed = |pos: &mut usize, tag: &str| -> Result<String, String> {
        let header = next_line(pos)?;
        let len_str = header
            .strip_prefix(&format!("{tag} "))
            .ok_or_else(|| format!("expected '{tag} <len>' line, got {header:?}"))?;
        let len: usize = len_str
            .parse()
            .map_err(|_| format!("malformed {tag} length in {header:?}"))?;
        let end = pos
            .checked_add(len)
            .filter(|&e| e <= bytes.len())
            .ok_or_else(|| format!("{tag} payload overruns the cert"))?;
        let payload = String::from_utf8(bytes[*pos..end].to_vec())
            .map_err(|_| format!("{tag} payload is not UTF-8"))?;
        *pos = end;
        if *pos >= bytes.len() || bytes[*pos] != b'\n' {
            return Err(format!("{tag} payload missing its newline separator"));
        }
        *pos += 1;
        Ok(payload)
    };
    let hex_field = |line: &str, prefix: &str| -> Result<String, String> {
        let v = line
            .strip_prefix(prefix)
            .ok_or_else(|| format!("expected {prefix:?} line, got {line:?}"))?;
        if v.len() != 64
            || !v
                .bytes()
                .all(|b| b.is_ascii_hexdigit() && !b.is_ascii_uppercase())
        {
            return Err(format!(
                "{prefix} value must be 64 lowercase hex chars, got {v:?}"
            ));
        }
        Ok(v.to_string())
    };

    let schema = next_line(&mut pos)?;
    // v3 carries the obligation text; v2 does not. Both are accepted on READ
    // (see LRAT_CERT_SCHEMA_LINE_V2); v3 is what render_cert MINTS.
    let is_v3 = schema == LRAT_CERT_SCHEMA_LINE;
    if !is_v3 && schema != LRAT_CERT_SCHEMA_LINE_V2 {
        return Err(format!(
            "unrecognized schema line {schema:?} (expected {LRAT_CERT_SCHEMA_LINE:?}              or {LRAT_CERT_SCHEMA_LINE_V2:?})"
        ));
    }
    let verdict_key = hex_field(&next_line(&mut pos)?, "verdict-sha256: ")?;
    let solver_identity = hex_field(&next_line(&mut pos)?, "solver-sha256: ")?;
    let cnf_sha256 = hex_field(&next_line(&mut pos)?, "cnf-sha256: ")?;
    let name_line = next_line(&mut pos)?;
    let obligation_name = name_line
        .strip_prefix("obligation: ")
        .ok_or_else(|| format!("expected 'obligation: <name>' line, got {name_line:?}"))?
        .to_string();
    if obligation_name.is_empty() {
        return Err("empty obligation name".to_string());
    }
    let cnf = framed(&mut pos, "cnf")?;
    let drat = framed(&mut pos, "drat")?;
    // v2 has no `smt2` section; it parses to the empty string, which
    // `carries_obligation_binding()` reports as "binding not carried".
    let smt2 = if is_v3 {
        framed(&mut pos, "smt2")?
    } else {
        String::new()
    };
    if pos != bytes.len() {
        return Err("trailing bytes after cert".to_string());
    }
    // Enforce the integrity binding at parse time: header hash MUST match the
    // recorded CNF. A cert claiming a hash it cannot reproduce is rejected.
    let actual = sha256_hex(cnf.as_bytes());
    if actual != cnf_sha256 {
        return Err(format!(
            "cnf-sha256 header {cnf_sha256} disagrees with recorded CNF (hashes to {actual})"
        ));
    }
    Ok(LratCert {
        verdict_key,
        solver_identity,
        obligation_name,
        cnf_sha256,
        cnf,
        drat,
        smt2,
    })
}

