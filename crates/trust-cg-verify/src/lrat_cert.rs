//! **ENC-6 — independent-checker backstop for the ay UNSAT verdicts.**
//!
//! A tier-0 DB row (`crate::verdict_db`) records that `ay` once answered
//! `unsat` for a fixed query. The compile path treats that row only as a
//! candidate and re-runs the solver before crediting it; writable recorded
//! output is not proof authority. ENC-6 provides a machine-checkable offline
//! alternative by attaching a DRAT proof that an **independent** checker
//! (`drat-trim`, Marijn Heule, MIT — vendored as `trust-cg-drat-trim`) verifies.
//!
//! # Why this shrinks the trusted island
//!
//! The 4th trusted island is "ay UNSAT verdicts + statistical >8-bit
//! discharge". For a `QF_BV` obligation, ay does two jobs:
//!
//!  1. **bit-blast** the SMT2 to a DIMACS CNF, and
//!  2. **refute** that exact CNF (a SAT search), emitting a DRAT proof.
//!
//! Both artifacts are transactionally published by one authenticated AY run
//! (`ay solve <smt2> --dump-bv-cnf <cnf> --proof <drat>`); trust-cg never
//! re-solves a detached CNF in a second process.
//!
//! `drat-trim` independently confirms job (2): it replays the DRAT against the
//! CNF and derives the empty clause, i.e. the CNF **is** UNSAT — no trust in
//! ay's SAT engine required. The bit-blast (job 1, SMT2→CNF) stays in the ay
//! TCB; this is exactly the "ay bit-blaster + drat-trim TCB" that ENC-8 names as
//! the intended anchor for the large (v2i64-class) obligations the clean kernel
//! cannot scale to. So ENC-6 does not eliminate the island, it *shrinks* it: the
//! combinatorially-hard half of every certified verdict becomes independently
//! re-checkable.
//!
//! # Schema binding
//!
//! A cert carries the SAME `verdict_key` a tier-0 row uses
//! ([`crate::ay_bridge::verdict_cache_key_v2`] over the solver identity and the
//! byte-identical `crate::verdict_db::db_obligation_smt2` query), so a cert
//! provably backs a *specific* verdict-DB row and can never be silently
//! re-pointed at a different obligation.
//!
//! # Scope / cost
//!
//! This is an **opt-in / offline** lane. Nothing here runs on the per-compile
//! hot path; candidate rows are currently revalidated with live ay instead of
//! consuming these certificates. Certificate *generation* shells out to `ay`;
//! certificate *re-checking* shells out to `drat-trim`. Both executables are
//! passed in as paths, so the library carries **no** production dependency on
//! either — tests supply the vendored `drat-trim` (dev-dependency) and the
//! resolved `ay` binary.
//!
//! # Teeth
//!
//! A cert that "verifies" the wrong obligation is worse than nothing.
//! [`recheck_cert`] therefore (a) re-derives the recorded CNF's SHA-256 and
//! refuses a cert whose CNF bytes were altered, and (b) requires `drat-trim` to
//! print `s VERIFIED` at a success exit — a tampered proof yields `s NOT
//! VERIFIED` at a non-zero exit and is rejected. Both are covered by the module
//! tests.

use std::path::Path;
use std::process::Command;

use sha2::{Digest, Sha256};

/// Schema line every serialized cert file starts with.
pub const LRAT_CERT_SCHEMA_LINE: &str = "tcg-lrat-cert-v3";

/// The predecessor schema, still ACCEPTED on read.
///
/// v2 certs carry no `smt2` section, so they cannot be checked against the
/// obligation they name — [`LratCert::carries_obligation_binding`] reports
/// false for them and [`recheck_cert`] skips that check rather than pretending
/// to perform it. They are otherwise re-checked exactly as before, so accepting
/// them is status quo, not a weakening.
///
/// Both versions are accepted because the committed canary certificates are
/// `include_str!`-embedded and can only be regenerated by a machine with a
/// working `ay` (`cargo run --release -p trust-cg-verify --bin
/// regen_canary_certs`). Minting v3 while still reading v2 lets the binding
/// arrive without stranding the repo on an environment it cannot reproduce.
pub const LRAT_CERT_SCHEMA_LINE_V2: &str = "tcg-lrat-cert-v2";

/// Exit code a DIMACS-mode SAT solve returns for UNSATISFIABLE (the SAT
/// competition convention; 10 is SATISFIABLE). A DIMACS run therefore reports
/// success-as-refutation via a NON-zero status, so `ExitStatus::success()` must
/// not be used to gate it.
const DIMACS_UNSAT_EXIT: i32 = 20;

/// Lowercase-hex SHA-256 of `bytes`, matching the digest spelling used by
/// [`crate::ay_bridge::verdict_cache_key_v2`] and `solver_identity_hash`.
pub fn sha256_hex(bytes: &[u8]) -> String {
    format!("{:x}", Sha256::digest(bytes))
}

/// The outcome of an independent `drat-trim` re-check.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum DratTrimOutcome {
    /// `drat-trim` replayed the proof against the CNF and derived the empty
    /// clause: the formula is independently confirmed UNSAT.
    Verified,
    /// `drat-trim` ran but did NOT confirm UNSAT (tampered / insufficient
    /// proof, or a satisfiable formula). Carries the checker's reason line(s).
    NotVerified(String),
    /// The check could not be performed (missing binary, I/O failure, CNF
    /// integrity mismatch). NOT a verdict — the caller must not credit it.
    Error(String),
}

impl DratTrimOutcome {
    /// True only for [`DratTrimOutcome::Verified`]. Use this to gate crediting:
    /// `NotVerified` and `Error` are both non-credits.
    pub fn is_verified(&self) -> bool {
        matches!(self, DratTrimOutcome::Verified)
    }
}

/// A machine-checkable certificate that a specific Formal verdict's `QF_BV`
/// obligation is UNSAT.
///
/// Self-contained: it records the exact bit-blasted CNF and the DRAT proof, so
/// [`recheck_cert`] re-runs `drat-trim` with no other inputs. The `verdict_key`
/// ties it to a `verdict_db` tier-0 row; `cnf_sha256` binds the recorded CNF to
/// the proof so neither can be swapped without detection.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LratCert {
    /// The v2 verdict key of the row this cert backs
    /// (`verdict_cache_key_v2(solver_identity, obligation_smt2)`).
    pub verdict_key: String,
    /// Lowercase-hex SHA-256 of the `ay` solver binary that produced the proof.
    pub solver_identity: String,
    /// Diagnostic obligation name (informational).
    pub obligation_name: String,
    /// Lowercase-hex SHA-256 of `cnf` (integrity binding CNF↔proof).
    pub cnf_sha256: String,
    /// The bit-blasted DIMACS CNF from AY's transactional proof run.
    pub cnf: String,
    /// The DRAT proof published for `cnf` by that same AY run.
    pub drat: String,
    /// The SMT2 obligation text this cert certifies (schema v3).
    ///
    /// # Why the TEXT and not a hash
    ///
    /// A `smt2_sha256` field would be redundant: `verdict_key` is already
    /// `SHA256("tcg-proof-cache-v2\0" || solver_identity || "\0" || smt2)`
    /// (`ay_bridge::verdict_cache_key_v2`), and the consume path derives that key
    /// in-process from the LIVE obligation, so a key hit already implies
    /// byte-identical SMT2. Storing a second digest of the same bytes proves
    /// nothing new.
    ///
    /// Storing the TEXT is what actually shrinks the trusted link. The two-run
    /// split (SMT2 -> CNF, then CNF -> DRAT) means `drat-trim` no longer
    /// incidentally cross-checks that the recorded CNF really is this
    /// obligation's bit-blasting — the DRAT is derived from whatever bytes sit at
    /// `cnf_path`. With the SMT2 in the artifact an OFFLINE auditor can re-run
    /// the bit-blast and diff it against the recorded CNF, which is the only
    /// thing that closes that correspondence gap without trusting AY's export
    /// transaction. AY's exporter writes no digest of the query at all.
    pub smt2: String,
}

impl LratCert {
    /// Whether this cert carries the schema-v3 obligation binding (its own SMT2
    /// text), so `recheck_cert` can re-derive `verdict_key` from it.
    ///
    /// False for legacy v2 artifacts. A caller that requires the correspondence
    /// property — "this CNF is THIS obligation's bit-blasting", the half
    /// `drat-trim` stopped covering when generation split into two AY runs —
    /// must gate on this rather than assume every cert provides it.
    pub fn carries_obligation_binding(&self) -> bool {
        !self.smt2.is_empty()
    }

    /// Construct a cert, computing `cnf_sha256` from `cnf`.
    pub fn new(
        verdict_key: impl Into<String>,
        solver_identity: impl Into<String>,
        obligation_name: impl Into<String>,
        cnf: impl Into<String>,
        drat: impl Into<String>,
        smt2: impl Into<String>,
    ) -> Self {
        let cnf = cnf.into();
        let cnf_sha256 = sha256_hex(cnf.as_bytes());
        LratCert {
            verdict_key: verdict_key.into(),
            solver_identity: solver_identity.into(),
            obligation_name: obligation_name.into(),
            cnf_sha256,
            cnf,
            drat: drat.into(),
            smt2: smt2.into(),
        }
    }
}

// ---------------------------------------------------------------------------
// Independent re-check (the teeth)
// ---------------------------------------------------------------------------

/// Interpret a `drat-trim` run. `drat-trim` prints `s VERIFIED` on a confirmed
/// UNSAT and `s NOT VERIFIED` otherwise; on a good proof it exits 0, on a bad
/// one it exits non-zero. We require BOTH signals to agree on success and treat
/// any disagreement conservatively as a non-credit, so a future upstream that
/// changed one signal alone can never be mistaken for a pass.
fn interpret_drat_trim(output: &std::process::Output) -> DratTrimOutcome {
    let stdout = String::from_utf8_lossy(&output.stdout);
    let stderr = String::from_utf8_lossy(&output.stderr);
    let says_not_verified = stdout.contains("NOT VERIFIED") || stderr.contains("NOT VERIFIED");
    let says_verified =
        !says_not_verified && (stdout.contains("s VERIFIED") || stdout.contains("\nVERIFIED"));
    if output.status.success() && says_verified {
        DratTrimOutcome::Verified
    } else if says_not_verified || !output.status.success() {
        // A concrete rejection (bad/insufficient proof or SAT formula).
        let reason: String = stdout
            .lines()
            .filter(|l| {
                l.contains("NOT VERIFIED")
                    || l.contains("ERROR")
                    || l.contains("conflict")
                    || l.starts_with("s ")
            })
            .collect::<Vec<_>>()
            .join("; ");
        DratTrimOutcome::NotVerified(if reason.is_empty() {
            format!("drat-trim exit {:?}", output.status.code())
        } else {
            reason
        })
    } else {
        // Ran, exit 0, but no VERIFIED banner: ambiguous → non-credit.
        DratTrimOutcome::Error(format!(
            "drat-trim produced no VERIFIED banner (exit {:?})",
            output.status.code()
        ))
    }
}

/// Run the vendored `drat-trim` at `drat_trim_exe` on `cnf_path` + `proof_path`
/// and interpret the result. This is the INDEPENDENT half of ENC-6: no ay code
/// participates, so a `Verified` here is a check ay did not perform.
pub fn drat_trim_check(
    drat_trim_exe: &Path,
    cnf_path: &Path,
    proof_path: &Path,
) -> DratTrimOutcome {
    let output = match Command::new(drat_trim_exe)
        .arg(cnf_path)
        .arg(proof_path)
        .output()
    {
        Ok(o) => o,
        Err(e) => {
            return DratTrimOutcome::Error(format!(
                "spawning drat-trim ({}) failed: {e}",
                drat_trim_exe.display()
            ));
        }
    };
    interpret_drat_trim(&output)
}

/// Re-check a recorded cert with an independent `drat-trim`. Rejects (with
/// [`DratTrimOutcome::Error`]) BEFORE spawning the checker if the recorded CNF
/// bytes no longer hash to `cnf_sha256` — a tampered CNF can never reach the
/// checker paired with a proof that was made for the original CNF.
///
/// `workdir` is where the CNF/proof are materialized for the subprocess; use a
/// fresh temp dir per call.
pub fn recheck_cert(cert: &LratCert, drat_trim_exe: &Path, workdir: &Path) -> DratTrimOutcome {
    let actual = sha256_hex(cert.cnf.as_bytes());
    if actual != cert.cnf_sha256 {
        return DratTrimOutcome::Error(format!(
            "cnf integrity mismatch: recorded cnf_sha256={} but recorded CNF hashes to {actual}",
            cert.cnf_sha256
        ));
    }
    // OBLIGATION BINDING (schema v3). Re-derive the verdict key from the
    // RECORDED SMT2 and solver identity and require it to reproduce the recorded
    // key. Without this a cert is only self-consistent: it says "this DRAT
    // refutes this CNF" and names a verdict key, with nothing tying that key to
    // the obligation text in the same artifact. An auditor could not tell a cert
    // for obligation A carrying B's key from a genuine one.
    //
    // This is cheap (one SHA-256, no solver) and it is the half `drat-trim`
    // stopped covering when the generation path split into two AY runs — the
    // DRAT is derived from whatever bytes sit at `cnf_path`, so drat-trim
    // verifies job 2 (this CNF is UNSAT) but no longer incidentally guards job 1
    // (this CNF is THIS obligation's bit-blasting).
    // A v2 (legacy) cert carries no obligation text, so this check is not
    // performable. It is SKIPPED, never faked — `carries_obligation_binding()`
    // reports the difference so a caller can require the stronger property.
    let expected_key = crate::ay_bridge::verdict_cache_key_v2(&cert.solver_identity, &cert.smt2);
    if cert.carries_obligation_binding() && expected_key != cert.verdict_key {
        return DratTrimOutcome::Error(format!(
            "obligation binding mismatch: recorded verdict_key={} but (solver_identity, smt2) \
             derives {expected_key} — this cert does not certify the obligation it records",
            cert.verdict_key
        ));
    }
    if let Err(e) = std::fs::create_dir_all(workdir) {
        return DratTrimOutcome::Error(format!("cannot create workdir {}: {e}", workdir.display()));
    }
    let cnf_path = workdir.join("cert.cnf");
    let proof_path = workdir.join("cert.drat");
    if let Err(e) = std::fs::write(&cnf_path, cert.cnf.as_bytes()) {
        return DratTrimOutcome::Error(format!("cannot write {}: {e}", cnf_path.display()));
    }
    if let Err(e) = std::fs::write(&proof_path, cert.drat.as_bytes()) {
        return DratTrimOutcome::Error(format!("cannot write {}: {e}", proof_path.display()));
    }
    drat_trim_check(drat_trim_exe, &cnf_path, &proof_path)
}

