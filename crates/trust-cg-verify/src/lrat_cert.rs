    #[test]
    fn cert_for_a_different_obligation_is_rejected() {
        let dir = temp_dir("v3_binding");
        // A genuine, fully checkable cert...
        let good = golden_cert();
        assert!(
            recheck_cert(&good, drat_trim(), &dir.join("good")).is_verified(),
            "the consistent fixture must still verify"
        );

        // ...with ONLY the obligation text swapped. The CNF, the DRAT and the
        // key are untouched, so `drat-trim` would still say VERIFIED and the
        // cnf_sha256 integrity check still passes. Only the binding catches it.
        let mut forged = good.clone();
        forged.smt2 = "(set-logic QF_BV)\n(assert false)\n(check-sat)\n".to_string();
        let outcome = recheck_cert(&forged, drat_trim(), &dir.join("forged"));
        assert!(
            !outcome.is_verified(),
            "a cert whose key does not derive from its recorded obligation must NOT verify"
        );
        match outcome {
            DratTrimOutcome::Error(msg) => assert!(
                msg.contains("obligation binding mismatch"),
                "expected the binding diagnostic, got: {msg}"
            ),
            other => panic!("expected an Error verdict, got {other:?}"),
        }

        // Symmetrically: keeping the obligation but forging the KEY must fail.
        let mut wrong_key = good.clone();
        wrong_key.verdict_key = DUMMY_KEY.to_string();
        assert!(
            !recheck_cert(&wrong_key, drat_trim(), &dir.join("wrongkey")).is_verified(),
            "a cert carrying a key its own obligation does not derive must NOT verify"
        );

        let _ = std::fs::remove_dir_all(&dir);
    }

