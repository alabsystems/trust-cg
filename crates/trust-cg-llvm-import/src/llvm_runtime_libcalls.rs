/// Whether `name` is a runtime library call of
/// [`LLVM_AARCH64_RUNTIME_LIBCALLS`].
pub(crate) fn is_llvm_aarch64_runtime_libcall(name: &str) -> bool {
    LLVM_AARCH64_RUNTIME_LIBCALLS.binary_search(&name).is_ok()
}
