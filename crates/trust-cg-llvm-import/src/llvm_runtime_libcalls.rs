/// code generator may call for an operation the module states: `__udivti3`
/// for an `i128` `udiv`, `__floattidf` for an `i128` `sitofp`, `fmod` for
/// `frem`, `__exp10` for `exp10` on Darwin, `ldexp` for `FLDEXP`, the outline
