/// the availability predicate it is listed under: names listed only for
/// Darwin (`bzero`, `__exp10`, `memset_pattern16`), for Windows
/// (`__chkstk`), for OpenBSD (`__guard_local`) or for an SjLj exception
/// model are here too, so the table is a superset of the Linux and the
/// Darwin set, read without evaluating LLVM's predicates. Sorted by byte,
/// one entry per name.
///
