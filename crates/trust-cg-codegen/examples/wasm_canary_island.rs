//! The P0 wasm canary island (designs/2026-08-24-one-module-every-target.md
//! §4, trust repo): ONE pure `u32×u32→u32` function — a modulo-gcd loop (the
//! two-back-edge shape that surfaced the relooper's gcd bug) feeding eight
//! rounds of data-dependent branchy mixing, each round closing with a
//! "straddle" step selected by the UNSIGNED compare `a <u b` on the raw data
//! operands — memory-free, import-free, call-free, single-result. Compiled
//! here trust-ir→trust-cg-wasm and shipped beside the LLVM-built aterm engine
//! on alab.systems/terminal as an explicitly DIFFERENTIAL-EXPERIMENTAL island:
//! the page instantiates both this module and the rustc/LLVM twin of the same
//! spec and compares them, input by input, against the interpreter
//! expectations baked here.
//!
//! That straddle compare is why the corpus is full-width. A signed compare
//! answers differently for exactly the pairs whose operands straddle the sign
//! bit, so an `Ult`→`Slt` drift on DATA changes the answer here, rather than
//! hiding behind a loop bound that is never negative — and `main` proves it
//! rather than claiming it, by building the `Slt` mutant of this same spec and
//! demanding it diverge on every straddling pair and on no other.
//!
//! One file authors every spelling of the spec: the trust-ir builder below,
//! the Rust twin source (`TWIN_RS`, emitted alongside for the vanilla lane),
//! and the interpreter reference (which executes the builder's Module). Any
//! drift between spellings is exactly what the page's differential exists to
//! catch — a divergence is a miscompile or a spec-copy bug, and both are
//! failures.
//!
//!     scripts/trust_cargo.sh run --example wasm_canary_island -- <outdir>
//!
//! writes `<outdir>/canary_island.wasm` (trust-cg bytes, NO wasm-opt — island
//! policy is that shipped bytes are exactly the emitted bytes),
//! `<outdir>/canary_twin.rs` (the twin source for rustc/LLVM), and
//! `<outdir>/canary_expected.json` (4096 LCG + 18 edge inputs with
//! interpreter-computed answers).

use std::io::Write;

use trust_cg_codegen::wasm;
use trust_ir::{BinOp, ICmpOp, InterpretOptions, InterpretValue, Interpreter, Ty};
use trust_ir_build::ModuleBuilder;

/// The spec, prose spelling (u32, all arithmetic modular):
///
/// ```text
/// canary(a, b):
///   (x, y) = (a, b)
///   while y != 0 { (x, y) = (y, x mod y) }          # unsigned gcd
///   h = x ^ 0x9E3779B9
///   for i in 0..8:
///     match h & 3:
///       0 => h = (h + a*0x85EBCA6B) ^ (h >> 13)     # logical shift
///       1 => h = (h ^ b*0xC2B2AE35) + (h << 5)
///       2 => h = (h * 0x27D4EB2F) ^ (a + b)
///       _ => h = (h - (a ^ b)) ^ (h >> 7)
///     h = h ^ (i * 0x7FEB352D)
///     if a <u b:                                    # UNSIGNED, on the DATA
///       h = (h * 0xCC9E2D51) ^ (h >> 15)            # the straddle round
///   return h
/// ```
const TWIN_RS: &str = r#"// GENERATED by trust-cg's examples/wasm_canary_island.rs — the rustc/LLVM
// twin of the canary spec. Do not edit by hand; regenerate instead.
#![no_std]
// A wasm `unreachable` TRAPS. Never spin here: the twin is panic-free today,
// but a future spec edit that introduced a panic path would hang the page's
// differential (and the build gate) instead of failing it loudly.
#[panic_handler]
fn panic(_: &core::panic::PanicInfo) -> ! {
    core::arch::wasm32::unreachable()
}

#[unsafe(no_mangle)]
pub extern "C" fn canary(a: u32, b: u32) -> u32 {
    let (mut x, mut y) = (a, b);
    while y != 0 {
        let r = x % y;
        x = y;
        y = r;
    }
    let mut h = x ^ 0x9E37_79B9;
    let mut i: u32 = 0;
    while i < 8 {
        h = match h & 3 {
            0 => (h.wrapping_add(a.wrapping_mul(0x85EB_CA6B))) ^ (h >> 13),
            1 => (h ^ b.wrapping_mul(0xC2B2_AE35)).wrapping_add(h << 5),
            2 => h.wrapping_mul(0x27D4_EB2F) ^ a.wrapping_add(b),
            _ => (h.wrapping_sub(a ^ b)) ^ (h >> 7),
        };
        h ^= i.wrapping_mul(0x7FEB_352D);
        // UNSIGNED, and on the DATA: `a` and `b` are u32, so this is the one
        // compare in the spec whose signedness is observable. It answers
        // differently from a signed compare for exactly the pairs that
        // straddle the sign bit — never write `as i32` here.
        if a < b {
            h = h.wrapping_mul(0xCC9E_2D51) ^ (h >> 15);
        }
        i += 1;
    }
    h
}
"#;

/// Fixed edge-case inputs exercised ahead of the LCG corpus. The last two are
/// the MINIMAL sign-bit straddle: `a <u b` and `a <s b` disagree on both, so a
/// signedness drift in the straddle round cannot slip past the edge set even
/// if the LCG corpus were ever replaced.
const EDGES: &[(u32, u32)] = &[
    (0, 0),
    (0, 1),
    (1, 0),
    (1, 1),
    (u32::MAX, u32::MAX),
    (u32::MAX, 1),
    (1, u32::MAX),
    (0x8000_0000, 3),
    (3, 0x8000_0000),
    (0x9E37_79B9, 0x85EB_CA6B),
    (2, 4),
    (6, 9),
    (600, 600),
    (0xFFFF, 0x1_0001),
    (0x8000_0000, 0x8000_0000),
    (123_456_789, 987_654_321),
    (0x7FFF_FFFF, 0x8000_0000),
    (0x8000_0000, 0x7FFF_FFFF),
];

const LCG_PAIRS: usize = 4096;

struct Lcg(u64);
impl Lcg {
    /// FULL-WIDTH u32 output. The obvious `(state >> 33) as u32` yields only
    /// 31 bits, so every "random" operand would clear the high bit and the
    /// corpus would never exercise half the u32 domain — precisely where an
    /// unsigned-vs-signed compare drift hides. XOR-folding both halves keeps
    /// the high bits live.
    fn next(&mut self) -> u32 {
        self.0 = self
            .0
            .wrapping_mul(6364136223846793005)
            .wrapping_add(1442695040888963407);
        ((self.0 >> 32) as u32) ^ (self.0 as u32)
    }
}

/// Build the canary. `straddle_cmp` is the spec's ONE data-dependent compare;
/// the shipped island always passes `ICmpOp::Ult` (the spec). `main` also
/// builds the `ICmpOp::Slt` MUTANT and demands it diverge, which is what turns
/// "this corpus would catch an unsigned→signed drift" from a claim in a commit
/// message into something checked on every regeneration.
fn build_canary(mb: &mut ModuleBuilder, straddle_cmp: ICmpOp) -> trust_ir::FuncId {
    let sig = mb.add_func_type(vec![Ty::I32, Ty::I32], vec![Ty::I32]);
    let mut fb = mb.function("canary", sig);

    let entry = fb.create_block();
    let ghead = fb.create_block(); // gcd loop header (x, y)
    let gstep = fb.create_block(); // gcd body (x, y), y != 0
    let mixin = fb.create_block(); // gcd result -> mixer seed (g)
    let round = fb.create_block(); // mix loop header (h, i)
    let t1 = fb.create_block(); //    sel cascade (h, i, sel)
    let t2 = fb.create_block(); //    sel cascade (h, i, sel)
    let r0 = fb.create_block(); //    round bodies (h, i)
    let r1 = fb.create_block();
    let r2 = fb.create_block();
    let r3 = fb.create_block();
    let join = fb.create_block(); //   (h', i)
    let strd = fb.create_block(); //   straddle round (h, i) — taken when a <u b
    let latch = fb.create_block(); //  (h, i) -> i += 1, back edge
    let exit = fb.create_block(); //   (h)

    let a = fb.add_block_param(entry, Ty::I32);
    let b = fb.add_block_param(entry, Ty::I32);
    let gx = fb.add_block_param(ghead, Ty::I32);
    let gy = fb.add_block_param(ghead, Ty::I32);
    let sx = fb.add_block_param(gstep, Ty::I32);
    let sy = fb.add_block_param(gstep, Ty::I32);
    let g = fb.add_block_param(mixin, Ty::I32);
    let h = fb.add_block_param(round, Ty::I32);
    let i = fb.add_block_param(round, Ty::I32);
    let t1h = fb.add_block_param(t1, Ty::I32);
    let t1i = fb.add_block_param(t1, Ty::I32);
    let t1s = fb.add_block_param(t1, Ty::I32);
    let t2h = fb.add_block_param(t2, Ty::I32);
    let t2i = fb.add_block_param(t2, Ty::I32);
    let t2s = fb.add_block_param(t2, Ty::I32);
    let r0h = fb.add_block_param(r0, Ty::I32);
    let r0i = fb.add_block_param(r0, Ty::I32);
    let r1h = fb.add_block_param(r1, Ty::I32);
    let r1i = fb.add_block_param(r1, Ty::I32);
    let r2h = fb.add_block_param(r2, Ty::I32);
    let r2i = fb.add_block_param(r2, Ty::I32);
    let r3h = fb.add_block_param(r3, Ty::I32);
    let r3i = fb.add_block_param(r3, Ty::I32);
    let jh = fb.add_block_param(join, Ty::I32);
    let ji = fb.add_block_param(join, Ty::I32);
    let sdh = fb.add_block_param(strd, Ty::I32);
    let sdi = fb.add_block_param(strd, Ty::I32);
    let lh = fb.add_block_param(latch, Ty::I32);
    let li = fb.add_block_param(latch, Ty::I32);
    let xh = fb.add_block_param(exit, Ty::I32);

    fb.switch_to_block(entry);
    fb.br(ghead, vec![a, b]);

    // while y != 0 { (x, y) = (y, x mod y) } — URem's divisor is the branch-
    // guarded nonzero y, so the op can never trap in any spelling.
    fb.switch_to_block(ghead);
    let z = fb.iconst(Ty::I32, 0);
    let ne = fb.icmp(ICmpOp::Ne, Ty::I32, gy, z);
    fb.condbr(ne, gstep, vec![gx, gy], mixin, vec![gx]);
    fb.switch_to_block(gstep);
    let rem = fb.binop(BinOp::URem, Ty::I32, sx, sy);
    fb.br(ghead, vec![sy, rem]);

    fb.switch_to_block(mixin);
    let golden = fb.iconst(Ty::I32, 0x9E37_79B9u32 as i32 as i128);
    let h0 = fb.binop(BinOp::Xor, Ty::I32, g, golden);
    let i0 = fb.iconst(Ty::I32, 0);
    fb.br(round, vec![h0, i0]);

    // for i in 0..8, data-dependent 4-way cascade on h & 3
    fb.switch_to_block(round);
    let eight = fb.iconst(Ty::I32, 8);
    let done = fb.icmp(ICmpOp::Ult, Ty::I32, i, eight);
    // done == (i < 8): true -> keep mixing, false -> exit
    let three = fb.iconst(Ty::I32, 3);
    let sel = fb.binop(BinOp::And, Ty::I32, h, three);
    let zero = fb.iconst(Ty::I32, 0);
    let is0 = fb.icmp(ICmpOp::Eq, Ty::I32, sel, zero);
    // structure: first gate the loop exit, then cascade on sel
    let cascade = fb.create_block();
    let ch = fb.add_block_param(cascade, Ty::I32);
    let ci = fb.add_block_param(cascade, Ty::I32);
    let cs = fb.add_block_param(cascade, Ty::I32);
    let c0 = fb.add_block_param(cascade, Ty::Bool);
    fb.condbr(done, cascade, vec![h, i, sel, is0], exit, vec![h]);

    fb.switch_to_block(cascade);
    fb.condbr(c0, r0, vec![ch, ci], t1, vec![ch, ci, cs]);

    fb.switch_to_block(t1);
    let one = fb.iconst(Ty::I32, 1);
    let is1 = fb.icmp(ICmpOp::Eq, Ty::I32, t1s, one);
    fb.condbr(is1, r1, vec![t1h, t1i], t2, vec![t1h, t1i, t1s]);

    fb.switch_to_block(t2);
    let two = fb.iconst(Ty::I32, 2);
    let is2 = fb.icmp(ICmpOp::Eq, Ty::I32, t2s, two);
    fb.condbr(is2, r2, vec![t2h, t2i], r3, vec![t2h, t2i]);

    // 0 => h = (h + a*0x85EBCA6B) ^ (h >> 13)
    fb.switch_to_block(r0);
    let k0 = fb.iconst(Ty::I32, 0x85EB_CA6Bu32 as i32 as i128);
    let m0 = fb.binop(BinOp::Mul, Ty::I32, a, k0);
    let s0 = fb.binop(BinOp::Add, Ty::I32, r0h, m0);
    let c13 = fb.iconst(Ty::I32, 13);
    let sh0 = fb.binop(BinOp::LShr, Ty::I32, r0h, c13);
    let n0 = fb.binop(BinOp::Xor, Ty::I32, s0, sh0);
    fb.br(join, vec![n0, r0i]);

    // 1 => h = (h ^ b*0xC2B2AE35) + (h << 5)
    fb.switch_to_block(r1);
    let k1 = fb.iconst(Ty::I32, 0xC2B2_AE35u32 as i32 as i128);
    let m1 = fb.binop(BinOp::Mul, Ty::I32, b, k1);
    let x1 = fb.binop(BinOp::Xor, Ty::I32, r1h, m1);
    let c5 = fb.iconst(Ty::I32, 5);
    let sh1 = fb.binop(BinOp::Shl, Ty::I32, r1h, c5);
    let n1 = fb.binop(BinOp::Add, Ty::I32, x1, sh1);
    fb.br(join, vec![n1, r1i]);

    // 2 => h = (h * 0x27D4EB2F) ^ (a + b)
    fb.switch_to_block(r2);
    let k2 = fb.iconst(Ty::I32, 0x27D4_EB2Fu32 as i32 as i128);
    let m2 = fb.binop(BinOp::Mul, Ty::I32, r2h, k2);
    let ab = fb.binop(BinOp::Add, Ty::I32, a, b);
    let n2 = fb.binop(BinOp::Xor, Ty::I32, m2, ab);
    fb.br(join, vec![n2, r2i]);

    // _ => h = (h - (a ^ b)) ^ (h >> 7)
    fb.switch_to_block(r3);
    let axb = fb.binop(BinOp::Xor, Ty::I32, a, b);
    let d3 = fb.binop(BinOp::Sub, Ty::I32, r3h, axb);
    let c7 = fb.iconst(Ty::I32, 7);
    let sh3 = fb.binop(BinOp::LShr, Ty::I32, r3h, c7);
    let n3 = fb.binop(BinOp::Xor, Ty::I32, d3, sh3);
    fb.br(join, vec![n3, r3i]);

    // h = h ^ (i * 0x7FEB352D)
    fb.switch_to_block(join);
    let k4 = fb.iconst(Ty::I32, 0x7FEB_352Du32 as i32 as i128);
    let m4 = fb.binop(BinOp::Mul, Ty::I32, ji, k4);
    let h4 = fb.binop(BinOp::Xor, Ty::I32, jh, m4);
    // if a <u b — the spec's only compare on DATA, and the reason the corpus
    // is full-width. `a` and `b` are entry params, so they dominate here and
    // nothing has to be threaded through the loop to reach them.
    let straddle = fb.icmp(straddle_cmp, Ty::I32, a, b);
    fb.condbr(straddle, strd, vec![h4, ji], latch, vec![h4, ji]);

    //   h = (h * 0xCC9E2D51) ^ (h >> 15)
    fb.switch_to_block(strd);
    let k5 = fb.iconst(Ty::I32, 0xCC9E_2D51u32 as i32 as i128);
    let m5 = fb.binop(BinOp::Mul, Ty::I32, sdh, k5);
    let c15 = fb.iconst(Ty::I32, 15);
    let sh5 = fb.binop(BinOp::LShr, Ty::I32, sdh, c15);
    let n5 = fb.binop(BinOp::Xor, Ty::I32, m5, sh5);
    fb.br(latch, vec![n5, sdi]);

    // i += 1
    fb.switch_to_block(latch);
    let one2 = fb.iconst(Ty::I32, 1);
    let i4 = fb.binop(BinOp::Add, Ty::I32, li, one2);
    fb.br(round, vec![lh, i4]);

    fb.switch_to_block(exit);
    fb.ret(vec![xh]);
    fb.build()
}

fn main() {
    let out = std::env::args()
        .nth(1)
        .unwrap_or_else(|| "/tmp/canary".to_string());
    std::fs::create_dir_all(&out).unwrap();

    let opts = InterpretOptions {
        fuel: 50_000_000,
        max_call_depth: 16,
        panic_strategy: trust_ir::interpret::PanicStrategy::Abort,
    };

    let mut mb = ModuleBuilder::new("canary_island");
    let fid = build_canary(&mut mb, ICmpOp::Ult);
    let mut module = mb
        .build()
        .expect("ModuleBuilder::build: the example module");
    let interp = Interpreter::with_module(&module).with_options(opts);

    // The MUTANT: the same spec with the straddle round's compare flipped to
    // signed. It is never compiled and never shipped — it exists only so the
    // loop below can prove that the corpus would actually catch that drift.
    let mut mut_mb = ModuleBuilder::new("canary_island_slt_mutant");
    let mut_fid = build_canary(&mut mut_mb, ICmpOp::Slt);
    let mut_module = mut_mb
        .build()
        .expect("ModuleBuilder::build: the example module");
    let mut_interp = Interpreter::with_module(&mut_module).with_options(opts);

    let mut inputs: Vec<(u32, u32)> = EDGES.to_vec();
    let mut rng = Lcg(0x243F_6A88_85A3_08D3); // pi, like the page deserves
    for _ in 0..LCG_PAIRS {
        inputs.push((rng.next(), rng.next()));
    }

    let mut in_json = String::from("{\"inputs\":[");
    let mut ex_json = String::from("],\"expected\":[");
    // Mutation-detectability tally for the straddle round's UNSIGNED compare.
    let mut straddling = 0usize;
    let mut detected = 0usize;
    for (k, &(a, b)) in inputs.iter().enumerate() {
        let args = || {
            vec![
                InterpretValue::int(Ty::I32, a as i32 as i128).unwrap(),
                InterpretValue::int(Ty::I32, b as i32 as i128).unwrap(),
            ]
        };
        let outcome = interp
            .execute_func(fid, args())
            .unwrap_or_else(|e| panic!("interp canary({a},{b}) failed: {e}"));
        let res = outcome.returns[0]
            .as_int()
            .expect("i32 result")
            .as_unsigned() as u32;

        // `a <u b` and `a <s b` answer differently for exactly the pairs whose
        // operands straddle the sign bit. On those the Slt mutant MUST produce
        // a different hash (or the drift is invisible and this exhibit is
        // lying); on every other pair the two compares agree, so the mutant
        // MUST agree exactly (or the spec has grown a SECOND signedness-
        // sensitive compare that nobody wrote down).
        let mres = mut_interp
            .execute_func(mut_fid, args())
            .unwrap_or_else(|e| panic!("interp slt-mutant canary({a},{b}) failed: {e}"))
            .returns[0]
            .as_int()
            .expect("i32 result")
            .as_unsigned() as u32;
        if (a < b) != ((a as i32) < (b as i32)) {
            straddling += 1;
            detected += usize::from(mres != res);
        } else {
            assert_eq!(
                mres, res,
                "the Slt mutant diverged on the NON-straddling pair ({a},{b}): \
                 the spec has a signedness-sensitive compare beyond the straddle round"
            );
        }

        if k > 0 {
            in_json.push(',');
            ex_json.push(',');
        }
        in_json.push_str(&format!("[{a},{b}]"));
        ex_json.push_str(&res.to_string());
    }
    assert!(
        straddling >= LCG_PAIRS / 8,
        "the corpus barely straddles the sign bit ({straddling} of {} pairs) — \
         an unsigned/signed drift would be near-invisible",
        inputs.len()
    );
    assert_eq!(
        detected,
        straddling,
        "the Slt mutant survived {} of {straddling} straddling pairs — the exhibit's \
         unsigned-compare claim is not carried by this corpus",
        straddling - detected
    );
    let json = format!("{in_json}{ex_json}]}}");

    // compile_module fail-closes on target-free modules; the interpreter above
    // fail-closes the other way (reference execution wants the canonical
    // 64-bit layout), so the wasm32 pin is stamped after interpretation.
    module.target_info = Some(wasm::wasm32_target_info());
    let bytes = wasm::compile_module_with_policy_and_license(
        &module,
        &trust_cg_codegen::wasm::WasmModulePolicy::closed(),
        &permit_unlicensed(),
    )
    .expect("compile_module");
    std::fs::File::create(format!("{out}/canary_island.wasm"))
        .unwrap()
        .write_all(&bytes)
        .unwrap();
    std::fs::File::create(format!("{out}/canary_twin.rs"))
        .unwrap()
        .write_all(TWIN_RS.as_bytes())
        .unwrap();
    std::fs::File::create(format!("{out}/canary_expected.json"))
        .unwrap()
        .write_all(json.as_bytes())
        .unwrap();
    eprintln!(
        "canary island: {} bytes of wasm, {} inputs ({straddling} straddle the sign bit, \
         all {detected} caught the Slt mutant), twin + expectations written to {out}/",
        bytes.len(),
        inputs.len()
    );
}

/// This file's fixtures are hand-built and carry no codegen license
/// (`body_gate: None`), which trust-cg REFUSES by default (roadmap WS7.5,
/// decision gate DG-73). Its compiles state `Permit` explicitly, so none of
/// them passes because it was silently refused.
fn permit_unlicensed() -> trust_cg_codegen::CodegenLicensePolicy {
    trust_cg_codegen::CodegenLicensePolicy::default()
        .with_unlicensed(trust_cg_codegen::UnlicensedBodyPolicy::Permit)
}
