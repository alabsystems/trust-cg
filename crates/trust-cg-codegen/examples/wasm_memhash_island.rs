//! The P2 island: the first trust-cg module that reads a HOST's linear memory.
//!
//! P0 and P5 are pure and memory-free by construction — they prove the
//! toolchain path and the engine's own functions, but they never leave their
//! own module. P2's architecture slice (imports, index space, memory policy,
//! host-negotiated regions) exists so an island can live *inside* a host's
//! address space, and this is its demonstration:
//!
//! ```text
//! mem_hash(ptr: u32, words: u32) -> u32    // FNV-1a-32 over host WORDS
//! ```
//!
//! Words, not bytes, on purpose: sub-word (`i32.load8_u`) memory access is a
//! P3 rung the backend still fails closed on, and P2's slice is imports,
//! index space and memory policy — not the value domain. The island therefore
//! reads 4-byte-aligned `i32` words, which is exactly what today's op set
//! admits, and the alignment requirement joins the host contract below.
//!
//! It imports the host's memory (`trust:island/abi@1`.`memory` — the
//! normative island namespace; `OWNERSHIP.md` §4.2 forbids `env`), reads
//! `[ptr, ptr+4*words)`, writes
//! nothing, calls nothing, and needs no frame — so it exercises the imported
//! memory path without yet depending on the host-negotiated stack. The
//! obligations that shift to the host are stated in
//! `crates/trust-cg-codegen/src/wasm/OWNERSHIP.md` §1.3 and §6; the honest
//! phrase for this artifact is "island under a stated host contract", never
//! "verified module".
//!
//! The spec, stated ONCE and spelled three ways (this builder, the emitted
//! rustc/LLVM twin, and the JS reference in the site's runner):
//!
//! ```text
//! h = 0x811C9DC5
//! for i in 0..words:  h = (h XOR word_le[ptr + 4*i]) * 0x01000193  (mod 2^32)
//! return h                                    // ptr MUST be 4-byte aligned
//! ```
//!
//!     cargo run --example wasm_memhash_island -- <outdir>
//!
//! writes `memhash_island.wasm` (trust-cg bytes, NO wasm-opt), the twin source,
//! and `memhash_expected.json`. The expectations are computed by walking the
//! same spec over a deterministic corpus IN THIS FILE — the trust-ir
//! interpreter is not used here, because it would have to model the host's
//! memory, which is precisely the thing the host owns. The third spelling is
//! therefore the JS reference, and the runner checks all three.

use std::io::Write as _;

use trust_cg_codegen::wasm::{
    self, ISLAND_ABI_NAMESPACE, ISLAND_MEMORY_IMPORT, WasmMemoryPolicy, WasmModulePolicy,
    WasmStackPolicy,
};
use trust_ir::{BinOp, ICmpOp, Ty};
use trust_ir_build::ModuleBuilder;

/// The host memory the island binds, in the NORMATIVE island namespace.
/// `OWNERSHIP.md` §4.2 forbids `env` — it is the namespace wasm-bindgen glue
/// and wasm-ld defaults live in, so an island must be impossible to confuse
/// with host plumbing.
const IMPORT_MODULE: &str = ISLAND_ABI_NAMESPACE;
const IMPORT_MEMORY: &str = ISLAND_MEMORY_IMPORT;

/// The twin's namespace is NOT a choice: `wasm-ld --import-memory` fixes an
/// LLVM module's memory import at `env.memory`. The host therefore publishes
/// ONE memory object under BOTH names — the island's normative namespace and
/// the twin's forced one — which is what the manifest records so a runner
/// cannot accidentally hand the two modules different address spaces.
const TWIN_IMPORT_MODULE: &str = "env";

/// Pages of shared memory the differential must allocate (see `main`).
const SHARED_PAGES: u32 = 16;

const FNV_OFFSET: u32 = 0x811C_9DC5;
const FNV_PRIME: u32 = 0x0100_0193;

const TWIN_RS: &str = r#"// GENERATED by trust-cg's examples/wasm_memhash_island.rs — the rustc/LLVM
// twin of the P2 island spec. Do not edit by hand; regenerate instead.
//
// It imports the SAME host memory the trust-cg island does, so the two
// modules hash the same bytes of the same address space.
#![no_std]
// A wasm `unreachable` TRAPS: a panic must fail the differential loudly,
// never hang it.
#[panic_handler]
fn panic(_: &core::panic::PanicInfo) -> ! {
    core::arch::wasm32::unreachable()
}

#[unsafe(no_mangle)]
pub extern "C" fn mem_hash(ptr: u32, words: u32) -> u32 {
    let mut h: u32 = 0x811C_9DC5;
    let mut i: u32 = 0;
    while i < words {
        // SAFETY: the host contract (OWNERSHIP.md §1.3) makes
        // [ptr, ptr + 4*words) a valid, initialized, 4-byte-aligned and
        // stably-mapped window for the call's duration. The module does not
        // bounds-check or align-check it; a violation is a host contract
        // break whose backstop is the wasm trap.
        let w = unsafe { *((ptr + i * 4) as *const u32) };
        h = (h ^ w).wrapping_mul(0x0100_0193);
        i += 1;
    }
    h
}
"#;

/// The reference spelling, used to bake expectations. Little-endian word
/// loads, matching wasm's `i32.load` and the twin's `*const u32`.
fn mem_hash_ref(bytes: &[u8], ptr: u32, words: u32) -> u32 {
    let mut h = FNV_OFFSET;
    for i in 0..words {
        let at = (ptr + i * 4) as usize;
        let w = u32::from_le_bytes([bytes[at], bytes[at + 1], bytes[at + 2], bytes[at + 3]]);
        h = (h ^ w).wrapping_mul(FNV_PRIME);
    }
    h
}

fn build_mem_hash(mb: &mut ModuleBuilder) -> trust_ir::FuncId {
    let sig = mb.add_func_type(vec![Ty::I32, Ty::I32], vec![Ty::I32]);
    let mut fb = mb.function("mem_hash", sig);

    let entry = fb.create_block();
    let head = fb.create_block(); // (h, i)
    let body = fb.create_block(); // (h, i), i < len
    let exit = fb.create_block(); // (h)

    let ptr = fb.add_block_param(entry, Ty::I32);
    let words = fb.add_block_param(entry, Ty::I32);
    let hh = fb.add_block_param(head, Ty::I32);
    let hi = fb.add_block_param(head, Ty::I32);
    let bh = fb.add_block_param(body, Ty::I32);
    let bi = fb.add_block_param(body, Ty::I32);
    let xh = fb.add_block_param(exit, Ty::I32);

    fb.switch_to_block(entry);
    let seed = fb.iconst(Ty::I32, i128::from(FNV_OFFSET as i32));
    let zero = fb.iconst(Ty::I32, 0);
    fb.br(head, vec![seed, zero]);

    // while i <u words
    fb.switch_to_block(head);
    let more = fb.icmp(ICmpOp::Ult, Ty::I32, hi, words);
    fb.condbr(more, body, vec![hh, hi], exit, vec![hh]);

    // h = (h ^ load32(ptr + 4*i)) * PRIME ; i += 1
    fb.switch_to_block(body);
    let four = fb.iconst(Ty::I32, 4);
    let off = fb.binop(BinOp::Mul, Ty::I32, bi, four);
    let addr = fb.binop(BinOp::Add, Ty::I32, ptr, off);
    let word = fb.load(Ty::I32, addr);
    let mixed = fb.binop(BinOp::Xor, Ty::I32, bh, word);
    let prime = fb.iconst(Ty::I32, i128::from(FNV_PRIME as i32));
    let next_h = fb.binop(BinOp::Mul, Ty::I32, mixed, prime);
    let one = fb.iconst(Ty::I32, 1);
    let next_i = fb.binop(BinOp::Add, Ty::I32, bi, one);
    fb.br(head, vec![next_h, next_i]);

    fb.switch_to_block(exit);
    fb.ret(vec![xh]);
    fb.build()
}

/// The deterministic corpus: a xorshift32-filled page with planted all-zero
/// and all-0xFF runs, walked by windows chosen to hit the shapes a hash loop
/// trips on — empty, single byte, unaligned start and length, run boundaries,
/// and the page edge.
fn corpus_bytes(pages: u32) -> Vec<u8> {
    let mut bytes = vec![0u8; (pages * 65536) as usize];
    let mut x: u32 = 0x1234_5678;
    for slot in bytes.iter_mut() {
        x ^= x << 13;
        x ^= x >> 17;
        x ^= x << 5;
        *slot = (x & 0xFF) as u8;
    }
    for slot in bytes[1024..1024 + 256].iter_mut() {
        *slot = 0x00;
    }
    for slot in bytes[2048..2048 + 256].iter_mut() {
        *slot = 0xFF;
    }
    bytes
}

/// `(4-byte-aligned ptr, word count)` windows: empty, single word, the
/// planted all-zero and all-0xFF runs, and the last word of the page.
fn windows() -> Vec<(u32, u32)> {
    let mut cases: Vec<(u32, u32)> = vec![
        (0, 0),
        (0, 1),
        (0, 2),
        (4, 1),
        (4, 3),
        (1024, 64),
        (1024, 63),
        (1028, 63),
        (2048, 64),
        (2044, 66),
        (0, 250),
        (124, 1024),
        (0, 16383),
        (4, 16382),
        (65532, 1),
        (65536, 0),
    ];
    let mut s: u32 = 0x9E37_79B9;
    for _ in 0..200 {
        s = s.wrapping_mul(1_664_525).wrapping_add(1_013_904_223);
        let ptr = (s % 60_000) & !3;
        let words = (s >> 8) % 1024;
        cases.push((ptr, words));
    }
    cases
}

fn main() {
    let out = std::env::args()
        .nth(1)
        .unwrap_or_else(|| "/tmp/memhash".to_string());
    std::fs::create_dir_all(&out).unwrap();

    let mut mb = ModuleBuilder::new("memhash_island");
    let fid = build_mem_hash(&mut mb);
    let mut module = mb.build();
    module.target_info = Some(wasm::wasm32_target_info());

    // The P2 policy: the host's memory, no memory of our own, and no stack —
    // this island needs no frame, so it negotiates nothing beyond the region
    // its arguments name.
    let policy = WasmModulePolicy {
        memory: WasmMemoryPolicy::Imported {
            module: IMPORT_MODULE.to_string(),
            name: IMPORT_MEMORY.to_string(),
        },
        stack: WasmStackPolicy::OwnedTop,
        ..WasmModulePolicy::closed()
    };
    let bytes = wasm::compile_module_with_policy(&module, &policy).expect("compile_module");
    let _ = fid;

    // 16 pages, not 1: the LLVM twin's linker declares a 16-page minimum for
    // an imported memory (rustc reserves a 1 MiB shadow stack even for a
    // #![no_std] cdylib), so a smaller shared memory cannot instantiate BOTH
    // modules. The trust-cg island itself declares `min 0` and would take any
    // size — the requirement is the twin's, and the manifest records it so a
    // host knows what to allocate.
    let corpus = corpus_bytes(SHARED_PAGES);
    let cases = windows();
    let mut inputs = String::from("{\"twin_import\":[\"");
    inputs.push_str(TWIN_IMPORT_MODULE);
    inputs.push_str("\",\"");
    inputs.push_str(IMPORT_MEMORY);
    inputs.push_str("\"],\"import\":[\"");
    inputs.push_str(IMPORT_MODULE);
    inputs.push_str("\",\"");
    inputs.push_str(IMPORT_MEMORY);
    inputs.push_str(&format!(
        "\"],\"pages\":{SHARED_PAGES},\"unit\":\"words\",\"twin_link_args\":[\"--import-memory\"],\"windows\":["
    ));
    let mut expected = String::from("],\"expected\":[");
    for (k, &(ptr, words)) in cases.iter().enumerate() {
        let want = mem_hash_ref(&corpus, ptr, words);
        if k > 0 {
            inputs.push(',');
            expected.push(',');
        }
        inputs.push_str(&format!("[{ptr},{words}]"));
        expected.push_str(&want.to_string());
    }
    let json = format!("{inputs}{expected}]}}");

    std::fs::File::create(format!("{out}/memhash_island.wasm"))
        .unwrap()
        .write_all(&bytes)
        .unwrap();
    std::fs::File::create(format!("{out}/memhash_twin.rs"))
        .unwrap()
        .write_all(TWIN_RS.as_bytes())
        .unwrap();
    std::fs::File::create(format!("{out}/memhash_expected.json"))
        .unwrap()
        .write_all(json.as_bytes())
        .unwrap();
    eprintln!(
        "memhash island: {} bytes of wasm importing {IMPORT_MODULE}.{IMPORT_MEMORY}, \
         {} word-windows over a {}-byte corpus, twin + expectations written to {out}/",
        bytes.len(),
        cases.len(),
        corpus.len(),
    );
}
