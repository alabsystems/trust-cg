// test `trust_f5_norepr_call_clobbers_fixed_bl_blr` pins the FIXED behavior:
// no-repr JIT == native for all four call opcodes.
//
// REGENERATED for the 260-variant enum: with more than 256 variants rustc
// gives the no-repr enum a u16 tag, so this fixture now ALSO pins the u16
// no-repr tag read (Bl=71/Blr=72 below 128; BL=241/BLR=242 above — the
// formerly-F5-prone range).

