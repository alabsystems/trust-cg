// ── call_opcode_clobbers_registers (scheduler.rs:1011-1016, VERBATIM) ────────
fn call_opcode_clobbers_registers(opcode: AArch64Opcode) -> bool {
    matches!(
        opcode,
        AArch64Opcode::Bl | AArch64Opcode::Blr | AArch64Opcode::BL | AArch64Opcode::BLR
    )
}

