//! Homogeneous floating-point aggregates with zero-sized members on AArch64
//! (Linux floor target, with host-neutral rows the Darwin floor also runs).
//!
//! AAPCS64 homogeneity is judged after layout. GCC 13 on Linux AArch64 (and
//! clang's `isHomogeneousAggregate`) skip an empty-struct member, so
//! `struct { double a; struct {} z; double b, c, d; }` is an HFA of four
//! doubles passed in d0-d3, while a zero-length array member (`double z[0]`)
//! makes an aggregate non-homogeneous. trust-cg used to reject a struct with
//! more than four DECLARED fields before flattening, so it passed the first
//! shape by reference in x0 (2026-09-23: a C callee computed the wrong digest
//! at O0 and O2), and it ignored zero-length arrays, so it passed
//! `struct { float a; float z[0]; float b; }` in s0/s1 where GCC uses x0.
//!
//! The corpus (`fixtures/hfa_zero_sized`, generated by the report harness
//! `gen_hfa_zero_sized.py`) has nine shapes: `()` and empty-struct members
//! first, in the middle, last, nested and as an array of empty structs, and
//! three zero-length-array shapes. Each is exercised in four directions:
//! trust-cg passes it to C, C passes it to trust-cg, trust-cg returns it to C,
//! and C returns it to trust-cg.
//!
//! Host-neutral rows: the corpus is canonical trust-ir, the translated LIR
//! types classify as GCC places them, and the corpus compiles for Linux and
//! Darwin at O0-O3 (DarwinPCS shares the rule through clang's classifier; not
//! executed here). The Linux-only row links each level with `cc` against the
//! C oracle (`driver.c`). Execution evidence, not a proof.

use trust_cg_codegen::pipeline::OptLevel;
use trust_cg_codegen::target::TargetSpec;
use trust_cg_codegen::{Compiler, CompilerConfig};
use trust_cg_lower::abi::{AArch64AbiVariant, AppleAArch64ABI, ArgLocation, HfaBaseType};
use trust_ir::Module;

const CORPUS: &str = include_str!("fixtures/hfa_zero_sized/corpus.trust_ir");
const LINUX: &str = "aarch64-unknown-linux-gnu";
const DARWIN: &str = "aarch64-apple-darwin";
const LEVELS: [OptLevel; 4] = [OptLevel::O0, OptLevel::O1, OptLevel::O2, OptLevel::O3];

/// Each shape with its placement under `gcc -O2`: `Some((base, members))`
/// for an HFA, `None` for a non-homogeneous aggregate.
const SHAPES: &[(&str, Option<(HfaBaseType, usize)>)] = &[
    ("de", Some((HfaBaseType::F64, 4))),
    ("du", Some((HfaBaseType::F64, 4))),
    ("del", Some((HfaBaseType::F64, 4))),
    ("dea", Some((HfaBaseType::F64, 4))),
    ("dn", Some((HfaBaseType::F64, 3))),
    ("fe", Some((HfaBaseType::F32, 2))),
    ("da", None),
    ("fa0", None),
    ("da2", None),
];
/// Checks per shape in the driver: three inputs in three directions, and one
/// C-returned value. Read only by the Linux-native leg.
#[cfg(all(target_arch = "aarch64", target_os = "linux", target_env = "gnu"))]
const CHECKS_PER_SHAPE: usize = 10;

fn corpus_for(triple: &str) -> Module {
    let mut module = trust_ir::parser::parse_module(CORPUS).expect("the corpus parses");
    module
        .target_info
        .as_mut()
        .expect("the corpus declares a target")
        .triple = triple.into();
    module
}

fn compile(module: &Module, triple: &str, opt_level: OptLevel) -> Result<Vec<u8>, String> {
    Compiler::new_for_target_spec(
        CompilerConfig {
            opt_level,
            ..CompilerConfig::default()
        },
        TargetSpec::parse(triple).unwrap(),
    )
    .with_codegen_license(permit_unlicensed())
    .compile(module)
    .map(|output| output.object_code)
    .map_err(|error| format!("{error:?}"))
}

#[test]
fn corpus_is_canonical_trust_ir_defining_every_direction() {
    let module = corpus_for(LINUX);
    let errors = trust_ir_build::validate_module(&module);
    assert!(errors.is_empty(), "the corpus must validate: {errors:?}");
    for (name, _) in SHAPES {
        for prefix in ["cg_pass", "cg_take", "cg_ret", "cg_cret"] {
            let function = format!("{prefix}_{name}");
            assert!(
                module
                    .functions
                    .iter()
                    .any(|f| f.name == function && !f.blocks.is_empty()),
                "{function} is not defined"
            );
        }
    }
}

/// The translated LIR type of each shape (the `cg_take_*` parameter)
/// classifies as GCC places it, as an argument under both conventions and
/// as a return value.
#[test]
fn translated_shapes_classify_as_gcc_places_them() {
    let functions = permit_translate_module(&corpus_for(LINUX)).expect("the corpus lowers");
    for (name, want) in SHAPES {
        let take = format!("cg_take_{name}");
        let (function, _) = functions
            .iter()
            .find(|(f, _)| f.name == take)
            .unwrap_or_else(|| panic!("no lowered {take}"));
        let ty = &function.signature.params[0];
        assert_eq!(AppleAArch64ABI::classify_hfa(ty), *want, "{name}: {ty:?}");
        for variant in [AArch64AbiVariant::Aapcs64, AArch64AbiVariant::Darwin] {
            let locs = AppleAArch64ABI::classify_params_with(variant, std::slice::from_ref(ty));
            match (want, &locs[..]) {
                (Some((_, members)), [ArgLocation::RegSequence(regs)]) => {
                    assert_eq!(regs.len(), *members, "{name} {variant:?}")
                }
                (None, [ArgLocation::Indirect { .. }]) => assert!(ty.bytes() > 16, "{name}"),
                (None, [ArgLocation::Reg(_)]) => assert!(ty.bytes() <= 8, "{name}"),
                (None, [ArgLocation::RegPair(_, _)]) => assert_eq!(ty.bytes(), 16, "{name}"),
                other => panic!("{name} {variant:?}: unexpected placement {other:?}"),
            }
        }
        let returns = AppleAArch64ABI::classify_returns(std::slice::from_ref(ty));
        let hfa_return = matches!(&returns[..], [ArgLocation::RegSequence(_)]);
        assert_eq!(hfa_return, want.is_some(), "{name} returns {returns:?}");
    }
}

#[test]
fn corpus_compiles_for_linux_and_darwin_o0_through_o3() {
    for (triple, magic) in [
        (LINUX, &b"\x7fELF"[..]),
        (DARWIN, &[0xcf, 0xfa, 0xed, 0xfe][..]),
    ] {
        let module = corpus_for(triple);
        for level in LEVELS {
            let object = compile(&module, triple, level)
                .unwrap_or_else(|e| panic!("{triple} {level:?}: {e}"));
            assert_eq!(&object[..4], magic, "{triple} {level:?}");
        }
    }
}

#[cfg(all(target_arch = "aarch64", target_os = "linux", target_env = "gnu"))]
#[path = "common/rosetta.rs"]
mod process;

#[path = "common/fresh_dir.rs"]
mod fresh_dir;

#[cfg(all(target_arch = "aarch64", target_os = "linux", target_env = "gnu"))]
mod native {
    use super::{CHECKS_PER_SHAPE, LEVELS, LINUX, SHAPES, compile, corpus_for, fresh_dir, process};
    use std::fs;
    use std::path::PathBuf;
    use std::process::Command;

    const DRIVER: &str = include_str!("fixtures/hfa_zero_sized/driver.c");

    #[test]
    fn native_shapes_match_the_c_oracle_o0_through_o3() {
        let retain = std::env::var_os("TCG_HFA_ZERO_SIZED_RETAIN").map(PathBuf::from);
        let total = SHAPES.len() * CHECKS_PER_SHAPE;
        for level in LEVELS {
            let object = compile(&corpus_for(LINUX), LINUX, level).unwrap();
            let dir = fresh_dir::create("trust-cg-hfa-zero-sized-");
            let object_path = dir.join(format!("{level:?}.o"));
            let binary = dir.join(format!("driver-{level:?}"));
            fs::write(&object_path, &object).unwrap();
            fs::write(dir.join("driver.c"), DRIVER).unwrap();
            let link = process::command_output_with_timeout(
                Command::new("cc")
                    .args(["-O2", "-Wall", "-Werror"])
                    .arg(dir.join("driver.c"))
                    .arg(&object_path)
                    .arg("-o")
                    .arg(&binary),
                process::codegen_link_timeout(),
            )
            .unwrap();
            assert!(
                !link.timed_out && link.output.status.success(),
                "{level:?} link files={dir:?}: {}",
                String::from_utf8_lossy(&link.output.stderr)
            );
            let run = process::run_executable_with_timeout(&binary, process::codegen_run_timeout())
                .unwrap();
            assert!(!run.timed_out, "{level:?} timed out files={dir:?}");
            let stdout = String::from_utf8_lossy(&run.output.stdout).into_owned();
            if let Some(retain) = &retain {
                fs::create_dir_all(retain).unwrap();
                fs::write(retain.join(format!("{level:?}.o")), &object).unwrap();
                fs::write(retain.join(format!("{level:?}.stdout")), &stdout).unwrap();
            }
            let lines: Vec<&str> = stdout.lines().collect();
            for (name, _) in SHAPES {
                let want = format!("shape {name} checks={CHECKS_PER_SHAPE} failures=0 ok");
                assert!(
                    lines.contains(&want.as_str()),
                    "{level:?}: missing `{want}` files={dir:?}\n{stdout}"
                );
            }
            let summary = format!("hfa-zero-sized shapes_failed=0 checks={total} failures=0");
            assert_eq!(
                lines.last().copied(),
                Some(summary.as_str()),
                "{level:?} files={dir:?}\n{stdout}"
            );
            assert!(
                run.output.status.success(),
                "{level:?}: driver failed files={dir:?}\n{stdout}"
            );
            eprintln!("{level:?}: {summary}");
            fs::remove_dir_all(&dir).unwrap();
        }
    }
}

/// This file's fixtures are hand-built and carry no codegen license
/// (`body_gate: None`), which trust-cg REFUSES by default (roadmap WS7.5,
/// decision gate DG-73). Its compiles state `Permit` explicitly, so none of
/// them passes because it was silently refused.
fn permit_unlicensed() -> trust_cg_lower::CodegenLicensePolicy {
    trust_cg_lower::CodegenLicensePolicy::default()
        .with_unlicensed(trust_cg_lower::UnlicensedBodyPolicy::Permit)
}

/// `translate_module` under [`permit_unlicensed`].
fn permit_translate_module(
    module: &trust_ir::Module,
) -> Result<
    Vec<(trust_cg_lower::Function, trust_cg_lower::ProofContext)>,
    trust_cg_lower::AdapterError,
> {
    trust_cg_lower::translate_module_for_arch_with_tls_with_license(
        module,
        trust_cg_lower::GuardCarrierArch::default(),
        trust_cg_lower::TlsDialect::default(),
        &permit_unlicensed(),
    )
}
