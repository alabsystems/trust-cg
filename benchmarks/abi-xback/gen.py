#!/usr/bin/env python3
"""Generate a matched callee/caller pair for a cross-backend ABI differential.

Author: Andrew Yates <andrewyates.name@gmail.com>
Copyright 2026 Andrew Yates | License: Apache-2.0

WHY: every other differential gate in this repo compiles a WHOLE PROGRAM with a
single backend, so a calling-convention disagreement is invisible to all of them
-- both sides are wrong in the same way and agree with each other. The AArch64
stack-argument layout bug (Darwin natural-size packing applied to an ELF target,
where AAPCS64 stage C.14 mandates 8-byte slots) was found only by linking an
LLVM-compiled caller against a trust-cg-compiled callee.

Each seed emits a signature of 9..20 arguments using narrow and mixed-width
types where the two conventions disagree. Most seeds overflow one of the 8 GPR /
8 FPR argument banks onto the stack -- which is where the layout rules diverge
-- and the remainder still exercise register assignment. Overflow is frequent
across a seed corpus, not guaranteed per seed.

INVARIANT: callee and caller are generated by two SEPARATE invocations sharing
one seed, so they agree only because the draw sequence below is identical for
both roles. Do not add, remove or reorder any rng call without regenerating the
pinned corpus figures in README.md.

Usage:
  gen.py SEED callee|caller          one seed's pair (run.sh; exit code = folded % 251)
  gen.py --emit-group DIR FIRST COUNT
                                     seeds FIRST..FIRST+COUNT-1 as ONE callee crate
                                     (`xabi_<seed>`) and ONE caller crate that runs
                                     seed k when argc == k - FIRST + 2 and prints the
                                     whole folded u64, plus expected.json with the
                                     value this script computes for every seed
                                     (scripts/check_linux_aarch64_xback.py)

Both modes draw every seed through `draw()`, so a seed's signature, values and
return shape are the same in either.
"""

import json
from pathlib import Path
import random
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from families import CALLER_RUNTIME, live_across  # noqa: E402  (the shared no-fmt printer and live-across values)

# (rust type, inclusive low bound, inclusive high bound)
INT_TYPES = [
    ("u8", 0, 255),
    ("i8", -128, 127),
    ("u16", 0, 65535),
    ("i16", -32768, 32767),
    ("u32", 0, 4_000_000),
    ("i32", -2_000_000, 2_000_000),
    ("u64", 0, 9_000_000),
    ("i64", -9_000_000, 9_000_000),
    # 128-bit integers are here for their ALIGNMENT, not their width. AAPCS64
    # stage C.8 rounds the GPR index up to an EVEN register before allocating
    # the pair, so `(ptr, i128, i128)` lands at x0, x2:x3, x4:x5 and leaves x1
    # permanently dead. trust-cg omitted that round-up and packed them at
    # x1:x2 / x3:x4 -- see the C.8 note in trust-cg-lower/src/abi.rs. Both
    # sides of a trust-cg-only call agreed with each other, so only a
    # cross-backend differential like this one can see it.
    ("u128", 0, 2**100),
    ("i128", -(2**100), 2**100),
]
# Types whose value does not fit in a u64 and must be folded in two halves.
WIDE_TYPES = {"u128", "i128"}

# A 16-byte-ALIGNED aggregate. This is a distinct code path from the scalar
# above -- the classifier handles composites in their own arm -- and the C.8
# round-up has to be applied in both. Its 8-aligned sibling is the negative
# control: same 16 bytes, and it must NOT skip a register.
AGG_DECL = """#[repr(C)]
#[derive(Clone, Copy)]
pub struct A16 {
    pub x: i128,
}

#[repr(C)]
#[derive(Clone, Copy)]
pub struct A8 {
    pub a: i64,
    pub b: i64,
}

#[repr(C)]
#[derive(Clone, Copy)]
pub struct A24 {
    pub a: i64,
    pub b: i64,
    pub c: i64,
}
"""
AGG_TYPES = ["A16", "A8"]
FLOAT_TYPES = ["f32", "f64"]

# Return values cross the same boundary as arguments and take DIFFERENT paths:
# x0 for a scalar, x0:x1 for a 128-bit pair, and an indirect sret buffer whose
# pointer arrives in x8 for anything over 16 bytes. A gate that always returns
# u64 exercises exactly one of the three. Each entry is
# (rust type, expression building it from `acc`, expression folding it back).
RET_TYPES = [
    ("u64", "acc", "v"),
    (
        "i128",
        "((acc as i128) << 64) | (acc as i128 & 0xffff_ffff_ffff_ffff)",
        "(v as u64) ^ ((v >> 64) as u64).wrapping_mul(3)",
    ),
    (
        "A16",
        "A16 { x: ((acc as i128) << 64) | (acc as i128 & 0xffff_ffff_ffff_ffff) }",
        "(v.x as u64) ^ ((v.x >> 64) as u64).wrapping_mul(3)",
    ),
    (
        "A8",
        "A8 { a: acc as i64, b: (acc as i64).wrapping_mul(3) }",
        "(v.a as u64) ^ (v.b as u64).wrapping_mul(3)",
    ),
    (
        "A24",
        "A24 { a: acc as i64, b: (acc as i64).wrapping_mul(3), c: (acc as i64).wrapping_mul(7) }",
        "(v.a as u64) ^ (v.b as u64).wrapping_mul(3) ^ (v.c as u64).wrapping_mul(7)",
    ),
]


MASK = (1 << 64) - 1


def draw(seed: int) -> dict:
    """One seed's signature. The rng call order is the corpus (INVARIANT)."""
    rng = random.Random(seed)

    # 9..20 params: pushes past the 8 GPR / 8 FPR argument registers often
    # enough that a stack-slot layout error shows up across a seed corpus.
    nargs = rng.randrange(9, 21)
    params = []
    values = []
    # The same values as Python numbers, for the independent expected fold.
    raws = []
    for _ in range(nargs):
        if rng.random() < 0.25:
            ty = rng.choice(FLOAT_TYPES)
            # Small integral values: exactly representable in f32 and f64, so
            # the checksum is bit-identical on both sides.
            value = rng.randrange(-1000, 1000)
            params.append(ty)
            values.append(f"bb({value}.0{ty})")
            raws.append(value)
        elif rng.random() < 0.15:
            ty = rng.choice(AGG_TYPES)
            params.append(ty)
            if ty == "A16":
                x = rng.randrange(-(2**100), 2**100)
                values.append(f"A16 {{ x: bb({x}i128) }}")
                raws.append(x)
            else:
                a = rng.randrange(-9_000_000, 9_000_000)
                b = rng.randrange(-9_000_000, 9_000_000)
                values.append(f"A8 {{ a: bb({a}i64), b: bb({b}i64) }}")
                raws.append((a, b))
        else:
            ty, low, high = rng.choice(INT_TYPES)
            value = rng.randrange(low, high + 1)
            params.append(ty)
            values.append(f"bb({value}{ty})")
            raws.append(value)

    # Identical text serves as the callee's parameter list and the caller's
    # extern declaration; a mismatch between the two would itself be a bug.
    signature = ", ".join(f"p{i}: {ty}" for i, ty in enumerate(params))
    ret_ty, ret_build, ret_fold = rng.choice(RET_TYPES)

    # Order-sensitive checksum: a wrong stack slot changes the result.
    # Floats deliberately take the same `as i64 as u64` path as integers -- the
    # values above are exactly representable, so the cast is lossless and the
    # accumulator stays bit-identical across backends.
    body = ["    let mut acc: u64 = 0;"]
    for i, ty in enumerate(params):
        # Fold every bit that crossed the boundary. A 128-bit value read one
        # register too low still has a plausible LOW half, so checking only
        # `as i64` would let a pair-alignment error through on some values.
        if ty in WIDE_TYPES:
            body.append(f"    acc = acc.wrapping_mul(31).wrapping_add(p{i} as u64);")
            body.append(
                f"    acc = acc.wrapping_mul(31).wrapping_add((p{i} >> 64) as u64);"
            )
        elif ty == "A16":
            body.append(f"    acc = acc.wrapping_mul(31).wrapping_add(p{i}.x as u64);")
            body.append(
                f"    acc = acc.wrapping_mul(31).wrapping_add((p{i}.x >> 64) as u64);"
            )
        elif ty == "A8":
            body.append(f"    acc = acc.wrapping_mul(31).wrapping_add(p{i}.a as u64);")
            body.append(f"    acc = acc.wrapping_mul(31).wrapping_add(p{i}.b as u64);")
        else:
            body.append(
                f"    acc = acc.wrapping_mul(31).wrapping_add(p{i} as i64 as u64);"
            )
    body.append(f"    {ret_build}")
    return {
        "seed": seed, "params": params, "values": values, "raws": raws,
        "signature": signature, "ret_ty": ret_ty, "ret_fold": ret_fold, "body": body,
    }


def fold(acc: int, word: int) -> int:
    return (acc * 31 + word) & MASK


def expected_folded(drawn: dict) -> int:
    """The caller's `folded` value, computed here without any compiler."""
    acc = 0
    for ty, raw in zip(drawn["params"], drawn["raws"]):
        if ty in WIDE_TYPES or ty == "A16":
            acc = fold(acc, raw & MASK)
            acc = fold(acc, (raw >> 64) & MASK)
        elif ty == "A8":
            acc = fold(acc, raw[0] & MASK)
            acc = fold(acc, raw[1] & MASK)
        else:
            # `p as i64 as u64`; every float value is integral.
            acc = fold(acc, int(raw) & MASK)
    ret = drawn["ret_ty"]
    if ret == "u64":
        return acc
    if ret in ("i128", "A16"):
        # low half acc, high half acc: (v as u64) ^ ((v >> 64) as u64) * 3
        return acc ^ ((acc * 3) & MASK)
    if ret == "A8":
        # a = acc, b = acc * 3: (a as u64) ^ (b as u64) * 3
        return acc ^ ((acc * 9) & MASK)
    if ret == "A24":
        # a = acc, b = acc * 3, c = acc * 7
        return acc ^ ((acc * 9) & MASK) ^ ((acc * 49) & MASK)
    raise ValueError(f"no expected fold for return type {ret!r}")


def emit_pair(seed: int, which: str) -> None:
    drawn = draw(seed)
    signature, ret_ty, body = drawn["signature"], drawn["ret_ty"], drawn["body"]
    if which == "callee":
        print(AGG_DECL)
        print("#[no_mangle]")
        print(f'pub extern "C" fn xabi({signature}) -> {ret_ty} {{')
        print("\n".join(body))
        print("}")
    elif which == "caller":
        # Identical decl on both sides; a divergence here would be a harness
        # bug that makes the differential compare two different programs.
        print(AGG_DECL)
        print(f'extern "C" {{ fn xabi({signature}) -> {ret_ty}; }}')
        print("use std::hint::black_box as bb;")
        print("fn main() {")
        args = ", ".join(drawn["values"])
        print(f"    let v = unsafe {{ xabi({args}) }};")
        print(f"    let folded: u64 = {drawn['ret_fold']};")
        print("    std::process::exit((folded % 251) as i32);")
        print("}")
    else:
        # Fail closed: a typo'd role must not silently emit a caller, which
        # would make the harness compare a program against itself and PASS.
        raise ValueError(f"expected callee or caller, got {which!r}")


GROUP_ATTRS = "#![allow(unused, dead_code, improper_ctypes, improper_ctypes_definitions)]\n"


def emit_group(directory: Path, first: int, count: int) -> None:
    """Seeds first..first+count-1 as one callee crate and one caller crate.

    Each seed keeps its own `extern "C"` declaration in the caller and its own
    `#[no_mangle]` definition in the callee, so every call is the same FFI
    shape as the pair mode; the caller declares its own copies of the
    aggregates, like the pair mode's separate files.
    """
    if count < 1:
        raise ValueError("a group needs at least one seed")
    seeds = [draw(seed) for seed in range(first, first + count)]
    callee = ["// Generated by benchmarks/abi-xback/gen.py --emit-group; do not edit.\n",
              '#![crate_type = "rlib"]\n#![crate_name = "xcallee"]\n', GROUP_ATTRS, AGG_DECL]
    caller = ["// Generated by benchmarks/abi-xback/gen.py --emit-group; do not edit.\n",
              "#![no_main]\n", GROUP_ATTRS, AGG_DECL, "extern crate xcallee;\n",
              "use std::hint::black_box as bb;\n\n", CALLER_RUNTIME, "\n", 'extern "C" {\n']
    for drawn in seeds:
        name = f"xabi_{drawn['seed']}"
        callee.append("#[no_mangle]\n")
        callee.append(f'pub extern "C" fn {name}({drawn["signature"]}) -> {drawn["ret_ty"]} {{\n')
        callee.append("\n".join(drawn["body"]) + "\n}\n\n")
        caller.append(f"    fn {name}({drawn['signature']}) -> {drawn['ret_ty']};\n")
    caller.append("}\n\n")
    cases = []
    for index, drawn in enumerate(seeds):
        seed = drawn["seed"]
        args = ", ".join(drawn["values"])
        live_setup, live_fold, live_expected = live_across(seed)
        caller.append(
            "#[inline(never)]\n"
            f"fn case_{seed}() {{\n"
            + "".join(line + "\n" for line in live_setup) +
            f"    let v = unsafe {{ xabi_{seed}({args}) }};\n"
            f"    let folded: u64 = {drawn['ret_fold']};\n"
            "    let mut line = [0u8; 512];\n"
            "    let mut n = 0usize;\n"
            f'    put_str(&mut line, &mut n, b"seed{seed} folded=");\n'
            "    put_hex(&mut line, &mut n, folded);\n"
            + "".join(line + "\n" for line in live_fold) +
            "    emit_line(&mut line, n);\n"
            "}\n\n"
        )
        cases.append({
            "name": f"seed{seed}", "family": "random-scalar", "abi": "C", "argc": index + 2,
            "sides": "both",
            "rule": f"{len(drawn['params'])} arguments returning {drawn['ret_ty']}",
            "expected": f"seed{seed} folded={expected_folded(drawn):016x} live={live_expected:016x}",
        })
    # Case selection by argument COUNT keeps the dispatcher free of parsing.
    arms = "".join(f"        {case['argc']} => case_{seed['seed']}(),\n"
                   for case, seed in zip(cases, seeds))
    caller.append(
        "#[no_mangle]\n"
        'pub extern "C" fn main(argc: i32, _argv: *const *const u8) -> i32 {\n'
        "    match argc {\n" + arms + "        _ => return 3,\n    }\n    0\n}\n"
    )
    directory.mkdir(parents=True, exist_ok=False)
    (directory / "callee.rs").write_text("".join(callee))
    (directory / "caller.rs").write_text("".join(caller))
    group = {"group": f"seeds{first}-{first + count - 1}", "cases": cases}
    (directory / "expected.json").write_text(json.dumps(group, indent=1) + "\n")


def main() -> int:
    if sys.argv[1:2] == ["--emit-group"]:
        if len(sys.argv) != 5:
            raise SystemExit("usage: gen.py --emit-group DIR FIRST COUNT")
        emit_group(Path(sys.argv[2]), int(sys.argv[3]), int(sys.argv[4]))
        return 0
    seed = int(sys.argv[1])
    which = sys.argv[2]  # "callee" or "caller"
    emit_pair(seed, which)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
